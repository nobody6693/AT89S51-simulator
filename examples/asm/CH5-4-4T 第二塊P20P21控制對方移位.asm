;==== 5-4-4 思考題（第二塊）：P2.0、P2.1 下命令給第一塊，收到的值放到 LED ====
;
; 思考題要求（課本 5-36 頁）：
;   第一塊的 P2.0 是 on/off 切換開關：第二塊 LED 不亮時按一下 → 第二塊 LED 全亮；再按一下 → 全滅。
;   第二塊的 P2.0、P2.1 是開關：按第二塊的 P2.0 → 第一塊 LED 單燈左移；按第二塊的 P2.1 → 第一塊 LED 單燈右移。
;   （課本第二點後半印成「第二塊的 LED 呈現單燈右移」，但題目前面寫第二塊的開關控制第一塊的 LED，這裡照第一塊做。）
;
; 兩塊要燒不同的程式，所以有兩個檔；載入哪一個，另一個就自動燒到第二塊板子上：
;   CH5-4-4T 第一塊P20控制對方LED.asm、CH5-4-4T 第二塊P20P21控制對方移位.asm
; P2.0、P2.1 就是主板的按鈕 PB3、PB4（按下讀 0）。
; 「左移、右移」以板子上看到的方向為準：P1.0 在最左邊，所以往左是 RR A、往右是 RL A，跟指令名稱相反。
;
; 怎麼從範例（CH5-4-4 雙機互傳）改成這一塊：
; 1. 串列埠設定不動（Mode 2、SMOD=1）。範例「一直傳開關」改成「按一下才傳一筆」。
; 2. 收的部分跟範例一模一樣：RI 起來就把 SBUF 放到 LED，第一塊送 00H 就全亮、0FFH 就全滅。
; 3. 傳的是命令：P2.0 送 1（左移）、P2.1 送 2（右移）。每 10ms 看一次按鍵，比對前後狀態，順便防彈跳。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
LED	EQU	P1		;LED 輸出埠
SW0	EQU	P2.0		;【改】左移開關，就是主板的 PB3
SW1	EQU	P2.1		;【加】右移開關，就是主板的 PB4
PREV0	BIT	00H		;【加】SW0 上一次的狀態（1 = 放開）
PREV1	BIT	01H		;【加】SW1 上一次的狀態
;========================================
	ORG	0		;程式從 0 位址開始
START:	MOV	SCON,#10010000B	;設定為 Mode 2、REN=1、RI=0
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====1====0====0====1====0====0====0====0===
	ORL	PCON,#80H	;將 SMOD 設定為 1
	SETB	SW0		;【改】將 P2.0 設定為輸入功能
	SETB	SW1		;【加】將 P2.1 設定為輸入功能
	SETB	PREV0		;【加】開機當作開關是放開的
	SETB	PREV1		;【加】
LOOP:	MOV	R5,#20		;【改】20 × 0.5ms = 10ms
	CALL	DELAY500us	;【加】每 10ms 巡一次，同時濾掉按鍵彈跳
	JNB	RI,CHK0		;【改】還沒收到就去看開關
	MOV	LED,SBUF	;將所接收的資料輸出到 LED
	CLR	RI		;清除 RI 旗標
CHK0:	JB	SW0,UP0		;【加】SW0 是放開的
	JNB	PREV0,CHK1	;【加】一直按著，不重複送
	CLR	PREV0		;【加】這一次才是剛按下去
	MOV	SBUF,#1		;【改】傳命令 1 = 左移
	JMP	CHK1		;【加】
UP0:	SETB	PREV0		;【加】記下 SW0 放開了
CHK1:	JB	SW1,UP1		;【加】SW1 是放開的
	JNB	PREV1,LOOP	;【加】一直按著，不重複送
	CLR	PREV1		;【加】這一次才是剛按下去
	MOV	SBUF,#2		;【改】傳命令 2 = 右移
	JMP	LOOP		;【加】
UP1:	SETB	PREV1		;【加】記下 SW1 放開了
	JMP	LOOP		;回去繼續巡
;==== 延時副程式：R5 × 0.5ms ============================
DELAY500us:
D0:	MOV	R7,#250		;內迴圈 250 × 2us = 0.5ms
	DJNZ	R7,$		;2 個機械週期 × 250 次
	DJNZ	R5,D0		;外迴圈 R5 次
	RET			;返回呼叫處
	END
