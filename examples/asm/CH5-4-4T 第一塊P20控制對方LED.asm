;==== 5-4-4 思考題（第一塊）：P2.0 切換對方 LED，收到命令就單燈左移或右移 ====
;
; 思考題要求（課本 5-36 頁）：
;   第一塊的 P2.0 是 on/off 切換開關：第二塊 LED 不亮時按一下 → 第二塊 LED 全亮；再按一下 → 全滅。
;   第二塊的 P2.0、P2.1 是開關：按第二塊的 P2.0 → 第一塊 LED 單燈左移；按第二塊的 P2.1 → 第一塊 LED 單燈右移。
;   （課本第二點後半印成「第二塊的 LED 呈現單燈右移」，但題目前面寫第二塊的開關控制第一塊的 LED，這裡照第一塊做。）
;
; 兩塊要燒不同的程式，所以有兩個檔；載入哪一個，另一個就自動燒到第二塊板子上：
;   CH5-4-4T 第一塊P20控制對方LED.asm、CH5-4-4T 第二塊P20P21控制對方移位.asm
; P2.0、P2.1 就是主板的按鈕 PB3、PB4（按下讀 0）。
;
; 怎麼從範例（CH5-4-4 雙機互傳）改成這一塊：
; 1. 串列埠設定不動（Mode 2、SMOD=1）。範例「一直傳開關」改成「按一下才傳一筆」。
; 2. 主迴圈改成每 10ms 巡一次：看 RI、看開關、算時間。按鍵前後狀態比對，順便做到防彈跳。
; 3. 傳給第二塊的就是它 P1 要輸出的值：00H 全亮、0FFH 全滅（低態亮），第二塊直接照放，跟範例一樣。
; 4. 收到的是命令：1 = 左移（RL A）、2 = 右移（RR A）。每 10 次巡邏（0.1 秒）移一格。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
LED	EQU	P1		;LED 輸出埠
SW	EQU	P2.0		;【改】切換開關，就是主板的 PB3
PREV	BIT	00H		;【加】開關上一次的狀態（1 = 放開）
SEND	EQU	30H		;【加】下一次要送給第二塊的值
DIR	EQU	31H		;【加】目前的動作：0 = 不動、1 = 左移、2 = 右移
PAT	EQU	32H		;【加】LED 樣板
;========================================
	ORG	0		;程式從 0 位址開始
START:	MOV	SCON,#10010000B	;設定為 Mode 2、REN=1、RI=0
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====1====0====0====1====0====0====0====0===
	ORL	PCON,#80H	;將 SMOD 設定為 1
	SETB	SW		;【改】將 P2.0 設定為輸入功能
	SETB	PREV		;【加】開機當作開關是放開的
	MOV	SEND,#00H	;【加】第二塊一開始不亮，第一次按要送「全亮」
	MOV	DIR,#0		;【加】還沒收到命令，LED 不動
	MOV	R6,#10		;【加】10 次巡邏移一格
LOOP:	MOV	R5,#20		;【改】20 × 0.5ms = 10ms
	CALL	DELAY500us	;【加】每 10ms 巡一次，同時濾掉按鍵彈跳
	JBC	RI,RECEIVED	;檢查是否完成接收？
CHK_SW:	JB	SW,SW_UP	;【加】開關是放開的
	JNB	PREV,TICK	;【加】一直按著，不重複送
	CLR	PREV		;【加】這一次才是剛按下去
	MOV	A,SEND		;【加】取出要送的值
	MOV	SBUF,A		;傳給第二塊，它會直接放到 P1
	CPL	A		;【加】00H ↔ 0FFH，下一次就是相反的
	MOV	SEND,A		;【加】記下來
	JMP	TICK		;【加】
SW_UP:	SETB	PREV		;【加】記下開關放開了
TICK:	DJNZ	R6,LOOP		;【加】還不到 0.1 秒
	MOV	R6,#10		;【加】重新計數
	MOV	R2,DIR		;【加】看現在要做什麼
	MOV	A,PAT		;【加】取出樣板
	CJNE	R2,#1,TRY_R	;【加】不是左移，看看是不是右移
	RL	A		;【加】左移一格
	JMP	SHOW		;【加】
TRY_R:	CJNE	R2,#2,LOOP	;【加】也不是右移：還沒收到命令，LED 不動
	RR	A		;【加】右移一格
SHOW:	MOV	PAT,A		;【加】記下新樣板
	MOV	LED,A		;【加】輸出
	JMP	LOOP		;【改】回去繼續巡
;=== 收到第二塊的命令 ==================================
RECEIVED:	MOV	DIR,SBUF	;【改】收到的不是 LED 值，是命令（1 = 左移、2 = 右移）
	MOV	PAT,#0FEH	;【加】換命令就從 11111110 開始，只亮一顆
	MOV	LED,PAT		;【加】馬上亮第一顆
	JMP	CHK_SW		;【改】回去看開關
;==== 延時副程式：R5 × 0.5ms ============================
DELAY500us:
D0:	MOV	R7,#250		;內迴圈 250 × 2us = 0.5ms
	DJNZ	R7,$		;2 個機械週期 × 250 次
	DJNZ	R5,D0		;外迴圈 R5 次
	RET			;返回呼叫處
	END
