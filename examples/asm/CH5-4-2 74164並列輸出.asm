;==== 5-4-2 串列埠轉並列式輸出埠：P0 指撥開關經 74164 顯示在 8 顆 LED ====
;
; 電路：74164 接在 P3.0、P3.1（模擬器載入範例時會自動接上，LED 在板子下方的「串列埠外接」）
;   74164 第 1、2 腳 A、B    → P3.0 (RxD)   Mode 0 傳出時 RxD 是資料線
;   74164 第 8 腳 clock      → P3.1 (TxD)   移位脈波
;   74164 第 9 腳 clear 接 VCC、QA~QH 經 330Ω 接 8 顆 LED（低態亮）
;   P0 = 主板指撥開關（ON 讀 0）
;
; 原理：Mode 0 傳出時，資料寫進 SBUF 就自動送出，8 個脈波（8us）送完 TI 變 1 並產生中斷，
;   中斷副程式再讀一次開關、再放進 SBUF，就這樣一筆接一筆，主程式不用管，閒置就好。
;   先送的是 D0，後面每進一位就往後推一級，所以送完 D0 停在 QH、D7 停在 QA。
;   課本的電路板 DS1(左)~DS8(右) 接 QH~QA，也就是 D0~D7，跟主板 P1 的 LED 順序一樣。
;   開關 ON 讀到 0 → Q 輸出 0 → LED 亮。
;
; 注意：74164 沒有栓鎖，移位的那 8us 輸出也在變。範例連續一直送，所以真實的板子上
;   沒開的 LED 會有一點點微亮；5-4-2 思考題改成久久送一次就看不到了。
;
; 串列埠中斷向量在 0023H；IE = 10010000B 是 EA + ES。
;
DIPSW	EQU	P0		;指撥開關輸入埠
;========================================
	ORG	0		;程式從 0 位址開始
	JMP	START		;主程式跳至 START
	ORG	23H		;串列埠中斷向量
	JMP	S_INT		;跳至串列埠中斷副程式
START:	MOV	SCON,#0H	;設定為 mode 0、REN=0、RI=0
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====0====0====0====0====0====0====0====0===
	MOV	IE,#10010000B	;啟用串列埠中斷
	MOV	DIPSW,#0FFH	;將 P0 規畫為輸入埠
	MOV	A,DIPSW		;讀取指撥開關狀態
	MOV	SBUF,A		;將所要傳出資料放入 SBUF
	JMP	$		;主程式閒置
;=== 串列埠輸出中斷副程式 ======================
S_INT:	MOV	A,DIPSW		;讀取指撥開關狀態
	MOV	SBUF,A		;將所要傳出資料放入 SBUF
	CLR	TI		;清除傳出中斷旗標
	RETI			;返回主程式
	END
