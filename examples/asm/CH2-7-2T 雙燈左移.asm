;==== 2-7-2 思考題：兩顆燈一起移 ====
;
; 思考題要求：
; 改成兩顆燈同時亮、同時移動，方向也反過來（從 P1.7 P1.6 走向 P1.1 P1.0）。
;
; 怎麼從範例（CH2-7-2 LED移動電路）改成這一題：
; 1. 樣板 A：11111110B（亮一顆）改成 00111111B（bit7、bit6 是 0 → 亮兩顆）。
; 2. 移動方向反過來：RL（左旋）改成 RR（右旋）。
; 3. 旋轉後要把「跑出去又繞回來」的位元補成 1：RL 補 bit0（ORL A,#1），RR 要補 bit7（ORL A,#10000000B）。
; 4. 兩顆燈佔兩個位置，8 個位置只能走 6 步，R0 從 7 改成 6。
; 其餘一行都沒動，跟範例一樣。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
PB	EQU	P2.0		;按鈕
LED	EQU	P1		;LED 輸出埠
	ORG	0
START:	SETB	PB		;P2.0 規劃成輸入
	MOV	LED,#0FFH	;LED 全暗
	JNB	PB,LEFT		;按鈕按下 → 開始移動
	JMP	START		;沒按就等
;==== 單燈移動 7 步 =========================================
LEFT:	MOV	R0,#6		;【改】7 → 6：兩顆燈只能移 6 次
	MOV	A,#00111111B	;【改】bit7 bit6 = 0：P1.7 P1.6 兩顆亮
	MOV	LED,A		;輸出
LOOP:	CALL	DELAY300ms	;停 0.3 秒
	RR	A		;【改】RL → RR：右旋，兩個 0 往低位元移一格
	ORL	A,#10000000B	;【改】補回 bit7 = 1（原本補 bit0）
	MOV	LED,A		;輸出
	DJNZ	R0,LOOP		;7 步走完
	CALL	DELAY300ms	;最後那顆也停 0.3 秒
	JMP	START		;回去等下一次按鈕
;==== 延時副程式：0.3 秒 ==================================
; 三層迴圈：內 250 × 2us = 0.5ms，中 200 次 = 0.1 秒，外 3 次 = 0.3 秒
DELAY300ms:
	MOV	R5,#3		;外迴圈 3 次
D0:	MOV	R7,#200		;中迴圈 200 次
D1:	MOV	R6,#250		;內迴圈 250 次
	DJNZ	R6,$		;0.5ms
	DJNZ	R7,D1		;0.1 秒
	DJNZ	R5,D0		;0.3 秒
	RET
	END
