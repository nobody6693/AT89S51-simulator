;==== 2-7-2 思考題：改成雙燈左移 =====================
; 原題：單燈左移，如何改成雙燈左移？
;
; 注意「左移」有兩種講法，這塊板子上兩者剛好相反：
;   暫存器的左移 = RL A = 往高位元 = P1.0 → P1.7 = 板子上由左往右
;   板子上的左移 =          往低位元 = P1.7 → P1.0 = RR A
; 本板 P1.0 是最左邊的 DS1、P1.7 是最右邊的 DS8（絲印上印得很清楚）。
; 這裡取「眼睛看到的方向」：兩顆燈從最右邊往左邊跑，所以用 RR A。
;
; 作法：初值 00111111B（P1.6、P1.7 兩顆亮 = 最右邊的 DS7、DS8），
;       每次 RR A 往低位元轉一格，最高位補 1 讓離開的那顆熄掉。
;       兩顆燈從最右邊走到最左邊要 6 步，所以計數是 6。
PB	EQU	P2.0		;設定按鈕開關位址
LED	EQU	P1		;設定 LED 位址
;==== 主程式 =========================================
	ORG	0
START:	SETB	PB		;規劃輸入埠
	MOV	LED,#0FFH	;LED 全滅
	JNB	PB,LEFT		;按鈕按下則進行雙燈左移
	JMP	START
;==== 雙燈左移（畫面上由右往左）=======================
LEFT:	MOV	R0,#6		;兩顆燈走到最左邊需要 6 步
	MOV	A,#00111111B	;初值：P1.6、P1.7 兩顆亮（最右邊 DS7、DS8）
	MOV	LED,A
LOOP:	CALL	DELAY300ms
	RR	A		;往低位元轉 = 燈往畫面左邊移動
	ORL	A,#10000000B	;最高位補 1，讓右邊離開的那顆熄滅
	MOV	LED,A
	DJNZ	R0,LOOP		;未達 6 次則繼續
	CALL	DELAY300ms
	JMP	START		;回主程式，LED 全滅
;==== 延時副程式(0.3 秒) =============================
DELAY300ms:
	MOV	R5,#3
D0:	MOV	R7,#200
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	DJNZ	R5,D0
	RET
	END
