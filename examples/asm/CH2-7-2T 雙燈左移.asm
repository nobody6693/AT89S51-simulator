PB	EQU	P2.0
LED	EQU	P1
	ORG	0
START:	SETB	PB
	MOV	LED,#0FFH
	JNB	PB,LEFT
	JMP	START
LEFT:	MOV	R0,#6
	MOV	A,#00111111B
	MOV	LED,A
LOOP:	CALL	DELAY300ms
	RR	A
	ORL	A,#10000000B
	MOV	LED,A
	DJNZ	R0,LOOP
	CALL	DELAY300ms
	JMP	START
DELAY300ms:
	MOV	R5,#3
D0:	MOV	R7,#200
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	DJNZ	R5,D0
	RET
	END
