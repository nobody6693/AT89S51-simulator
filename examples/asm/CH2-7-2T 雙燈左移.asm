;==== 2-7-2 思考題：改成雙燈左移 =====================
; 原題：單燈左移，如何改成雙燈左移？
; 作法：初值由 11111110B 改成 11111100B（P1.0、P1.1 兩顆亮），
;       左移後補 1 的方式不變。因為兩顆燈要走到最左邊需要 6 步，
;       所以計數由 7 改成 6。
PB	EQU	P2.0		;設定按鈕開關位址
LED	EQU	P1		;設定 LED 位址
;==== 主程式 =========================================
	ORG	0
START:	SETB	PB		;規劃輸入埠
	MOV	LED,#0FFH	;LED 全滅
	JNB	PB,LEFT		;按鈕按下則進行雙燈左移
	JMP	START
;==== 雙燈左移 =======================================
LEFT:	MOV	R0,#6		;兩顆燈只需左移 6 次就到底
	MOV	A,#11111100B	;初值：P1.0、P1.1 兩顆亮
	MOV	LED,A
LOOP:	CALL	DELAY300ms
	RL	A		;左移(右邊補 0)
	ORL	A,#1		;最右邊補 1
	MOV	LED,A
	DJNZ	R0,LOOP		;未達 6 次則繼續左移
	CALL	DELAY300ms
	JMP	START		;回主程式，LED 全滅
;==== 延時副程式(0.3 秒) =============================
DELAY300ms:
	MOV	R5,#3
D0:	MOV	R7,#200
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	DJNZ	R5,D0
	RET
	END
