SEGP	EQU	P0
SCANP	EQU	P2
SEC_COUNT	EQU	20
T0X	EQU	50000
T1X	EQU	1500
M1TH0	EQU	50H
M1TL0	EQU	51H
M1TH1	EQU	52H
M1TL1	EQU	53H
COUNTS	EQU	54H
S0	EQU	60H
S1	EQU	61H
D0	EQU	62H
M0	EQU	63H
M1	EQU	64H
D1	EQU	65H
H0	EQU	66H
H1	EQU	67H
SCANCODE	EQU	68H
	ORG	0
	JMP	START
	ORG	0BH
	JMP	TIMER
	ORG	1BH
	JMP	SCAN
START:	MOV	SP,#30H
	MOV	IE,#10001010B
	MOV	TMOD,#00010001B
	MOV	COUNTS,#0
	MOV	S0,#0
	MOV	S1,#0
	MOV	D0,#10
	MOV	M0,#0
	MOV	M1,#0
	MOV	D1,#10
	MOV	H0,#0
	MOV	H1,#0
	MOV	SCANCODE,#0
	MOV	M1TH0,#HIGH(-T0X)
	MOV	TH0,M1TH0
	MOV	M1TL0,#LOW(-T0X)
	MOV	TL0,M1TL0
	MOV	M1TH1,#HIGH(-T1X)
	MOV	TH1,M1TH1
	MOV	M1TL1,#LOW(-T1X)
	MOV	TL1,M1TL1
	SETB	TR0
	SETB	TR1
	JMP	$
TIMER:	MOV	TH0,M1TH0
	MOV	TL0,M1TL0
	INC	COUNTS
	MOV	A,COUNTS
	CJNE	A,#SEC_COUNT,T0_0
	MOV	COUNTS,#0
	INC	S0
	MOV	A,S0
	CJNE	A,#10,T0_0
	MOV	S0,#0
	INC	S1
	MOV	A,S1
	CJNE	A,#6,T0_0
	MOV	S1,#0
	INC	M0
	MOV	A,M0
	CJNE	A,#10,T0_0
	MOV	M0,#0
	INC	M1
	MOV	A,M1
	CJNE	A,#6,T0_0
	MOV	M1,#0
	INC	H0
	MOV	A,H0
	CJNE	A,#4,T0_1
	MOV	A,H1
	CJNE	A,#2,T0_0
	MOV	H0,#0
	MOV	H1,#0
	JMP	T0_0
T0_1:	CJNE	A,#10,T0_0
	MOV	H0,#0
	INC	H1
T0_0:	RETI
SCAN:	MOV	TH1,M1TH1
	MOV	TL1,M1TL1
	MOV	SCANP,#0FFH
	MOV	A,SCANCODE
	ADD	A,#60H
	MOV	R0,A
	MOV	A,@R0
	MOV	DPTR,#CA_CODE
	MOVC	A,@A+DPTR
	MOV	SEGP,A
	MOV	DPTR,#SCAN_CODE
	MOV	A,SCANCODE
	MOVC	A,@A+DPTR
	MOV	SCANP,A
	INC	SCANCODE
	MOV	A,SCANCODE
	CJNE	A,#8,T1_0
	MOV	SCANCODE,#0
T1_0:	RETI
SCAN_CODE:
	DB	11111110B
	DB	11111101B
	DB	11111011B
	DB	11110111B
	DB	11101111B
	DB	11011111B
	DB	10111111B
	DB	01111111B
CA_CODE:
	DB	00000011B
	DB	10011111B
	DB	00100101B
	DB	00001101B
	DB	10011001B
	DB	01001001B
	DB	01000001B
	DB	00011111B
	DB	00000001B
	DB	00001001B
	DB	11111101B
	END
