;==== 5-4-3 思考題：單機自傳改用 Mode 3 ====
;
; 思考題要求：
; 範例採 Mode 1 傳輸，請試著改用 Mode 2、Mode 3 的工作模式。（Mode 2 是另一個檔）
;
; Mode 3 的格式跟 Mode 2 一樣是 11 位元（多第 9 位），鮑率跟 Mode 1 一樣由 Timer 1 決定，
; 所以 TH1=0F3H 一樣是 4808bps，一筆 11 位元約 2.29ms。
;
; 怎麼從範例（CH5-4-3 單機自傳）改成這一題：
; 1. SCON 改 11010000B（SM0=1、SM1=1 是 Mode 3），其他設定一行都不用動。
; 2. 在 CLR TI 前面加 JNB TI,$。
;
; 為什麼第 2 點一定要加：收方在第 9 位的中央就把 RI 設起來，這時傳方還在送第 9 位（TB8 = 0）。
;   Mode 1 的第 9 位就是停止位元，下一筆可以接著開始；Mode 3 後面還有一個停止位元，一位 208us，
;   程式不到 10us 就繞回來寫 SBUF，停止位元會被吃掉。第 9 位是 0，起始位元也是 0，中間沒有下降緣，
;   下一筆就收不到。（沒加這行的話，LED 永遠停在第一筆。）所以要等 TI，也就是等第 9 位送完。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
DIPSW	EQU	P0		;指撥開關輸入埠
LED	EQU	P1		;LED 輸出埠
;========================================
	ORG	0		;程式從 0 位址開始
START:	MOV	SCON,#11010000B	;【改】設定為 mode 3、REN=1、RI=0
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====1====1====0====1====0====0====0====0===
	; 產生鮑率
	MOV	TMOD,#20H	;將 Timer 1 設定 Mode 2（8 位元自動重載）
	ORL	PCON,#80H	;將 SMOD 設定為 1
	MOV	TH1,#0F3H	;鮑率設定為 4800bps
	SETB	TR1		;啟動 Timer 1
	MOV	DIPSW,#0FFH	;將 P0 設定為輸入功能
LOOP:	MOV	A,DIPSW		;讀取指撥開關狀態
	MOV	SBUF,A		;啟動串列埠
	JNB	RI,$		;檢查是否完成接收？完成接收，則 RI 串列輸入中斷
	CLR	RI		;清除 RI 旗標
	MOV	LED,SBUF	;將所接收的資料輸出到 LED
	JNB	TI,$		;【加】等第 9 位送完（原因見檔頭）
	CLR	TI		;清除 TI 旗標
	JMP	LOOP		;跳至 LOOP 形成一個迴圈
	END
