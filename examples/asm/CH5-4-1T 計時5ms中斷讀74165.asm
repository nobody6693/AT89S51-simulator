;==== 5-4-1 思考題：每 5ms 用計時器觸發 74165，收資料改用中斷副程式 ====
;
; 思考題要求：
; 範例的主程式一直忙著載入、接收，沒辦法做別的事。請改以計時器每隔 5ms 觸發 74165 載入，
; 串列埠的資料輸入也改用中斷副程式處理，主程式就可以專心做別的事或閒置。
;
; 怎麼從範例（CH5-4-1 74165並列輸入）改成這一題：
; 1. 開頭加上中斷向量：000BH 給 Timer 0、0023H 給串列埠。
; 2. SCON 改 #00H（REN 先關），設定 Timer 0 mode 1、5000us，IE 開 EA+ES+ET0，主程式 JMP $ 閒置。
; 3. 範例 LOOP 裡的「負脈波」搬進 Timer 0 中斷；原本的 CLR RI 換成 SETB REN 來開始收。
; 4. 範例的 MOV LED,SBUF 搬進串列埠中斷。
;
; 為什麼要多動 REN：Mode 0 只要 REN=1 且 RI=0 就會開始收。中斷裡一定要清 RI（不清會一直中斷），
; 但只清 RI 又會馬上再收一筆，而這時 74165 沒有重新載入，收到的全是 1，LED 就全滅了。
; 所以串列埠中斷先 CLR REN 再 CLR RI，等下一個 5ms 載入完才 SETB REN。
;
; 時序：Timer 0 計量 5000us，重載值 = 65536-5000 = -5000；mode 1 不會自動重載，每次中斷都要填回去。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
LED	EQU	P1		;LED 輸出埠
;========================================
T0X	EQU	5000		;【加】Timer 0 計量：5000us = 5ms
	ORG	0		;程式從 0 位址開始
	JMP	START		;【加】跳過中斷向量
	ORG	0BH		;【加】Timer 0 中斷向量
	JMP	T0_INT		;【加】
	ORG	23H		;【加】串列埠中斷向量
	JMP	S_INT		;【加】
START:	MOV	SCON,#00H	;【改】mode 0、REN=0、RI=0：先不收，等第一個 5ms
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====0====0====0====0====0====0====0====0===
	MOV	TMOD,#01H	;【加】Timer 0 設為 mode 1（16 位元）
	MOV	TH0,#HIGH(-T0X)	;【加】填入計量（高 8 位元）
	MOV	TL0,#LOW(-T0X)	;【加】填入計量（低 8 位元）
	MOV	IE,#10010010B	;【加】EA + ES + ET0
	SETB	TR0		;【加】啟動 Timer 0
	JMP	$		;【改】主程式閒置（要做別的事就寫在這裡）
;=== Timer 0 中斷：每 5ms 載入 74165 並開始接收 ========
T0_INT:	MOV	TH0,#HIGH(-T0X)	;【加】mode 1 不會自動重載，填回計量
	MOV	TL0,#LOW(-T0X)	;【加】
	CLR	P3.2		;輸出負脈波
	NOP			;擴大負脈波寬度
	NOP			;擴大負脈波寬度
	SETB	P3.2		;恢復高態
	SETB	REN		;【改】此時 RI=0，一開 REN 就開始送 8 個移位脈波
	RETI			;【加】返回主程式
;=== 串列埠中斷：8 位元收滿，資料送到 LED ==============
S_INT:	CLR	REN		;【加】先關接收，不然下一行清 RI 就又開始收了
	CLR	RI		;【加】清除 RI 旗標，不清會一直中斷
	MOV	LED,SBUF	;將串列輸入資料輸出到 LED
	RETI			;【加】返回主程式
	END
