;==== 5-4-4 雙機互傳：兩塊板子的開關互相顯示在對方的 LED ====
;
; 電路：兩塊 KT89S51 跳接（模擬器載入範例時第二塊會出現在板子下方的「串列埠外接」）
;   第一塊 RxD (P3.0) ← 第二塊 TxD (P3.1)
;   第一塊 TxD (P3.1) → 第二塊 RxD (P3.0)
;   兩塊的地線接在一起。兩塊燒的是同一支程式。
;
; 原理：Mode 2 不用計時器，SMOD=1 時鮑率 = OSC/32 = 375000bps，一位約 2.67us，一筆 11 位元約 29us。
;   全雙工：傳與收同時進行、互不相干，所以主迴圈只是輪流看兩個旗標：
;     RI 起來 → 對方的資料到了，放到自己的 LED
;     TI 起來 → 自己這筆送完了，回 LOOP 讀開關、送下一筆
;   JBC 是「位元是 1 就清掉並跳走」，一條指令同時檢查和清除旗標。
;
LED	EQU	P1		;LED 輸出埠
DIPSW	EQU	P0		;指撥開關輸入埠
;========================================
	ORG	0		;程式從 0 位址開始
START:	MOV	SCON,#10010000B	;設定為 Mode 2、REN=1、RI=0
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====1====0====0====1====0====0====0====0===
	ORL	PCON,#80H	;將 SMOD 設定為 1
	MOV	DIPSW,#0FFH	;將 P0 設定為輸入功能
LOOP:	MOV	A,DIPSW		;讀取指撥開關狀態
	MOV	SBUF,A		;啟動串列埠，開始傳送資料
WAIT:	JBC	RI,RECEIVED	;檢查是否完成接收？若完成接收，則 RI 串列輸入中斷
	JBC	TI,LOOP		;檢查是否完成傳送？若完成傳送，則重新開始
	JMP	WAIT		;跳至 WAIT 繼續接收資料
RECEIVED:	MOV	LED,SBUF	;將所接收的資料輸出到 LED
	CLR	RI		;清除 RI 旗標
	JMP	WAIT		;跳至 WAIT 繼續接收資料
	END
