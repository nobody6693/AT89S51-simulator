SEGP	EQU	P0
SCANP	EQU	P2
DIGITS	EQU	4
SCAN_TIME	EQU	2
SCAN_CODE	EQU	01111111B
SCAN_COUNT	EQU	100
START:	MOV	R5,#SCAN_COUNT
LOOP1:	MOV	R3,#SCAN_CODE
	MOV	R4,#0
LOOP0:	MOV	SCANP,#0FFH
	MOV	DPTR,#DISP_DATA
	MOV	A,R4
	MOVC	A,@A+DPTR
	MOV	DPTR,#CA_CODE
	MOVC	A,@A+DPTR
	MOV	SEGP,A
	MOV	SCANP,R3
	MOV	R7,#SCAN_TIME
	CALL	DELAYx500us
	MOV	A,R3
	RR	A
	MOV	R3,A
	INC	R4
	CJNE	R4,#DIGITS,LOOP0
	DJNZ	R5,LOOP1
	MOV	SCANP,#0FFH
	MOV	R7,#200
	CALL	DELAYx500us
	JMP	START
DELAYx500us:
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
DISP_DATA:
	DB	8,0,5,3
CA_CODE:
	DB	00000011B
	DB	10011111B
	DB	00100101B
	DB	00001101B
	DB	10011001B
	DB	01001001B
	DB	01000001B
	DB	00011111B
	DB	00000001B
	DB	00001001B
	END
