SEGP	EQU	P0
KEYP	EQU	P2
DIGITS	EQU	4
SCAN_TIME	EQU	1
BLANK	EQU	16
KEYCODE	EQU	56H
COL	EQU	55H
ROW	EQU	54H
DIG3	EQU	53H
DIG2	EQU	52H
DIG1	EQU	51H
DIG0	EQU	50H
START:	MOV	DIG3,#BLANK
	MOV	DIG2,#BLANK
	MOV	DIG1,#BLANK
	MOV	DIG0,#0
LOOP1:	MOV	KEYCODE,#0
	MOV	ROW,#0
	MOV	COL,#0
LOOP0:	MOV	SEGP,#0FFH
	MOV	DPTR,#SCAN_CODE
	MOV	A,COL
	MOVC	A,@A+DPTR
	MOV	KEYP,A
	MOV	A,#DIG0
	ADD	A,COL
	MOV	R0,A
	MOV	A,@R0
	MOV	DPTR,#CA_CODE
	MOVC	A,@A+DPTR
	MOV	SEGP,A
	MOV	A,KEYP
	CPL	A
	ANL	A,#0FH
	CJNE	A,#00000000B,ROW0
	JMP	NEXT
ROW0:	CJNE	A,#00000001B,ROW1
	MOV	ROW,#0
	JMP	OK
ROW1:	CJNE	A,#00000010B,ROW2
	MOV	ROW,#1
	JMP	OK
ROW2:	CJNE	A,#00000100B,ROW3
	MOV	ROW,#2
	JMP	OK
ROW3:	CJNE	A,#00001000B,OK
	MOV	ROW,#3
OK:	MOV	A,COL
	RL	A
	RL	A
	ADD	A,ROW
	MOV	KEYCODE,A
	MOV	DIG3,DIG2
	MOV	DIG2,DIG1
	MOV	DIG1,DIG0
	MOV	DIG0,KEYCODE
CHECK:	MOV	A,KEYP
	CPL	A
	ANL	A,#0FH
	JNZ	CHECK
NEXT:	MOV	R7,#SCAN_TIME
	CALL	DELAYx500us
	INC	COL
	MOV	A,COL
	CJNE	A,#DIGITS,AGAIN
	JMP	LOOP1
AGAIN:	JMP	LOOP0
DELAYx500us:
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
CA_CODE:
	DB	00000011B
	DB	10011111B
	DB	00100101B
	DB	00001101B
	DB	10011001B
	DB	01001001B
	DB	01000001B
	DB	00011111B
	DB	00000001B
	DB	00001001B
	DB	00000101B
	DB	11000001B
	DB	01100011B
	DB	10000101B
	DB	01100001B
	DB	01110001B
	DB	11111111B
SCAN_CODE:
	DB	11101111B
	DB	11011111B
	DB	10111111B
	DB	01111111B
	END
