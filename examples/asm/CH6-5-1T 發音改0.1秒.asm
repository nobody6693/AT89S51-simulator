;==== 6-5-1 思考題 1：碰一下發音 0.2 秒改成 0.1 秒 ====
;
; 思考題要求：
; 在此按一個鍵，將持續發音 0.2 秒，請改為 0.1 秒，再試試看，連續播放時，有何不同？
;
; 怎麼從範例（CH6-5-1 簡易電子琴）改成這一題：
;   0.2 秒是 DELAY 的外圈 R5 = 2 圈 × 0.1 秒來的，只要把 R5 改成 1，延時就變 0.1 秒。
;   其他全部不動。
;
; 改完有什麼不同：
;   - 碰一下的最短聲音從 0.2 秒變 0.1 秒，快速連續碰不同的鍵，音跟音比較不會黏在一起，
;     可以彈得比較快、比較清楚（例如生日快樂歌開頭兩個半拍的 Do）。
;   - 按住不放（杜邦線一直接觸）：兩種都聽起來是連續的長音。程式只是每 0.1（或 0.2）秒
;     回到 LOOP 重新播同一個音，中間只停幾十微秒，耳朵聽不出來。
;   - 放開之後，聲音最多再拖 0.1 秒就停（原本最多拖 0.2 秒）。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】標出來。
;
; ---- 以下是範例檔頭 ----
; 電路：主板就夠用，另外一條杜邦線
;   P2.0~P2.7 → 8 個琴鍵。杜邦線一端插 GND，另一端碰哪一支腳就是按哪一個鍵
;     模擬器：先點 GND 排針、再點 P2.x 就跳一條線過去（= 按住），再點一次 P2.x 拆掉（= 放開）；
;     P2.0、P2.1 剛好是主板按鈕 PB3、PB4，直接按也可以
;   P3.7 → 蜂鳴器（經 PNP 電晶體，寫 0 導通發聲，寫 1 不通電）
;
; 原理：用計時器產生音調。
;   頻率 f 的方波，每半週期 1/(2f) 秒翻轉一次。中音 Do 523Hz → 半週期 956us。
;   12MHz 時計時器每 1us 加 1，所以半週期幾 us 就填幾，取負值讓它往上數到溢位：
;     -956 = 0FC44H → TH0 = 0FCH、TL0 = 44H，956us 後溢位、進 TONE 中斷。
;   Timer 0 用 Mode 1（16 位元），不會自動重載，所以 TONE 一進來先把 TH0、TL0 填回去，
;   再用 XRL P3,#80H 只把 P3.7 反相。計時量另外存在 M1_TH、M1_TL，中斷才拿得到。
;   T_BASE 每個音佔一個字組（2 位元組，DW 先放高位元組），所以按鍵編號 ×2 就是表裡的位置。
;
; 流程：
;   1. 依序檢查 P2.0~P2.7，R0 記住是第幾個鍵（0~7）；都沒按就回頭再看
;   2. 查表取出計時量，存進 M1_TH、M1_TL 並填入 TH0、TL0，啟動 Timer 0 開始發聲
;   3. 延時 0.2 秒後停掉 Timer 0，回到 1。鍵還按著就再發 0.2 秒，聽起來是連續的長音；
;      所以碰一下最少也會響 0.2 秒
;   4. 每次回到 LOOP 先把 P3.7 設成 1，蜂鳴器不通電（防燙：電磁式蜂鳴器直流電阻很小，
;      一直通電會發燙）
;
; 同時碰兩個鍵：只會彈編號小的那個（先檢查到的）。
;
; 跟課本不一樣的地方：課本把音階表放在 _T_BASE 節段（SEGMENT / RSEG），這個模擬器的組譯器
;   不認得節段敘述，所以拿掉，表格改放到程式後面；指令一個都沒改。
;   課本 DELAY 最後一行註解寫「2*250*200*5us」，R5 其實是 2，延時是 0.2 秒。
;
KEYS	EQU	P2		;按鍵輸入埠（8 個琴鍵）
BUZZER	EQU	P3		;蜂鳴器輸出埠（蜂鳴器在 P3.7）
M1_TH	EQU	40H		;計時量暫存區之高 8 位元
M1_TL	EQU	41H		;計時量暫存區之低 8 位元
	ORG	0		;程式從 0 位址開始
	JMP	START		;跳至主程式開始
	ORG	0BH		;Timer 0 中斷向量位址
	JMP	TONE		;跳至 TONE 中斷副程式
START:	MOV	IE, #10000010B	;啟用 Timer 0 中斷（EA + ET0）
	MOV	TMOD, #01H	;設定 Timer 0 為 Mode 1（16 位元計時）
	MOV	KEYS, #0FFH	;規畫 KEYS 為輸入埠（先寫 1 才能讀）
LOOP:	ORL	BUZZER, #80H	;P3.7 = 1：關閉蜂鳴器（防燙）
	MOV	R0,#0		;按鍵指標歸零（Do）
	JNB	KEYS.0, PLAY	;P2.0 碰到地（讀到 0）→ 彈 Do
	INC	R0		;按鍵指標加 1（Re）
	JNB	KEYS.1, PLAY	;P2.1 碰到地（讀到 0）→ 彈 Re
	INC	R0		;按鍵指標加 1（Mi）
	JNB	KEYS.2, PLAY	;P2.2 碰到地（讀到 0）→ 彈 Mi
	INC	R0		;按鍵指標加 1（Fa）
	JNB	KEYS.3, PLAY	;P2.3 碰到地（讀到 0）→ 彈 Fa
	INC	R0		;按鍵指標加 1（So）
	JNB	KEYS.4, PLAY	;P2.4 碰到地（讀到 0）→ 彈 So
	INC	R0		;按鍵指標加 1（La）
	JNB	KEYS.5, PLAY	;P2.5 碰到地（讀到 0）→ 彈 La
	INC	R0		;按鍵指標加 1（Si）
	JNB	KEYS.6, PLAY	;P2.6 碰到地（讀到 0）→ 彈 Si
	INC	R0		;按鍵指標加 1（Do_1）
	JNB	KEYS.7, PLAY	;P2.7 碰到地（讀到 0）→ 彈 Do_1
	JMP	LOOP		;無按鍵，從頭開始
;==== PLAY：查表取出計時量，發聲 0.2 秒 ===================================
PLAY:	MOV	A,R0		;取回按鍵值（0~7）
	RL	A		;每個音佔 2 位元組，指標 = 按鍵值 × 2
	MOV	R1,A		;暫存指標
	MOV	DPTR, #T_BASE	;指向音階表
	MOVC	A,@A+DPTR	;讀取計時量之高 8 位元
	MOV	M1_TH, A	;存入計時量變數（中斷重載要用）
	MOV	TH0, M1_TH	;填入計時量之高 8 位元
	MOV	A,R1		;取回取碼指標
	INC	A		;下個位址 = 低 8 位元
	MOVC	A,@A+DPTR	;讀取計時量之低 8 位元
	MOV	M1_TL, A	;存入計時量變數
	MOV	TL0, M1_TL	;填入計時量之低 8 位元
	SETB	TR0		;啟動計時器（開始播音）
	CALL	DELAY		;呼叫延時副程式（延時 0.1 秒）
	CLR	TR0		;關閉計時器（停止播音）
	JMP	LOOP		;重新開始
;==== DELAY：延時 0.1 秒 ===================================================
DELAY:	MOV	R5, #1		;【改】外圈 2 → 1 圈：0.2 秒變 0.1 秒
DL1:	MOV	R6, #200	;中圈 R6 = 200
DL0:	MOV	R7, #250	;內圈 R7 = 250
	DJNZ	R7, $		;DJNZ 2us × 250 = 500us
	DJNZ	R6, DL0		;500us × 200 = 0.1 秒
	DJNZ	R5, DL1		;0.1 秒 × 1 = 0.1 秒
	RET		;返回
;==== TONE：Timer 0 中斷，每半週期翻轉一次蜂鳴器 ==========================
TONE:	MOV	TH0, M1_TH	;填入計時量之高 8 位元（Mode 1 不會自動重載）
	MOV	TL0, M1_TL	;填入計時量之低 8 位元
	XRL	BUZZER, #80H	;切換蜂鳴器：只把 P3.7 反相，P3 其他腳不動
	RETI		;返回
;==== 基本音階表：計時量 = -(半週期 us)，DW 先放高位元組 =======================
T_BASE:	;Do	Re	Mi	Fa
	DW	-956,	-852,	-759,	-716	;中音 Do 523Hz、Re 587Hz、Mi 659Hz、Fa 698Hz
	;So	La	Si	Do_1
	DW	-638,	-568,	-506,	-478	;So 784Hz、La 880Hz、Si 988Hz、高音 Do 1046Hz
	END
