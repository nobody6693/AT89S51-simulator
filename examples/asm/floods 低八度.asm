;==== Pantera - Floods Outro —— 蜂鳴器單音演奏（低八度版） ============
;
; 由 MIDI 轉出來的：node tools/mid2asm.mjs "Pantera - Floods Outro.mid" --oct=1
; 207 個音、共 45.2 秒，音域 G#2 ~ G5（已整體升 1 個八度）
; 跟 floods.asm 完全一樣的樂譜，只是整體低一個八度。壓電蜂鳴器在低音會小聲很多。
;
; 蜂鳴器只有一支腳，只有高低兩種狀態，所以原曲的和弦一律只留最高音，
; 力度與音色全部丟掉 —— 剩下的就是一條單音旋律線。
;
; 音高：Timer0 中斷翻轉 P3.7 產生方波
; 節拍：Timer1 輪詢計時，樂譜長度以 10ms 為單位
; 燈光：主板 P1 那 8 顆 LED 當音高條，音愈高亮愈多顆（不需要接任何線）
; 每個音尾巴留 6ms 靜音，連續的同音才分得開。
Buzzer	EQU	P3.7		;蜂鳴器
RELD_H	EQU	30H		;目前這個音的 Timer0 重載值(高位元組)
RELD_L	EQU	31H		;                          (低位元組)
;==== 中斷向量 =======================================
	ORG	0
	JMP	START
	ORG	0BH		;Timer0 溢位
	JMP	T0ISR
;==== 主程式 =========================================
	ORG	30H
START:	MOV	SP,#5FH
	SETB	Buzzer		;蜂鳴器初始狀態(不響)
	MOV	P1,#0FFH	;LED 全滅
	MOV	TMOD,#11H	;T0、T1 都用模式 1(16 位元)
	SETB	ET0		;開 Timer0 中斷(負責音高)
	SETB	EA
REPLAY:	MOV	R4,#HIGH(SONG)	;樂譜指標放 R4:R5，DPTR 要留給查表
	MOV	R5,#LOW(SONG)
NEXT:	MOV	DPH,R4
	MOV	DPL,R5
	CLR	A
	MOVC	A,@A+DPTR	;音高代號(0 = 休止符)
	MOV	R0,A
	MOV	A,#1
	MOVC	A,@A+DPTR	;長度(10ms 為單位)
	MOV	R1,A
	JZ	REPLAY		;長度 0 = 曲終，從頭再來
	MOV	A,R5		;樂譜指標前進兩個位元組
	ADD	A,#2
	MOV	R5,A
	CLR	A
	ADDC	A,R4
	MOV	R4,A
	CALL	PLAY
	JMP	NEXT
;==== 奏一個音：R0 = 音高代號，R1 = 長度 =============
PLAY:	MOV	A,R0
	JZ	PREST		;代號 0 = 休止符
	DEC	A
	MOV	R2,A		;R2 = 代號-1，要用三次
	RL	A		;音高表每個音兩個位元組
	MOV	DPTR,#TONES
	MOVC	A,@A+DPTR
	MOV	RELD_H,A
	MOV	A,R2
	RL	A
	INC	A
	MOV	DPTR,#TONES
	MOVC	A,@A+DPTR
	MOV	RELD_L,A
	MOV	A,R2		;燈條：音愈高亮愈多顆
	MOV	DPTR,#BARS
	MOVC	A,@A+DPTR
	MOV	P1,A
	MOV	TH0,RELD_H
	MOV	TL0,RELD_L
	SETB	TR0		;開始發聲
	SJMP	PBODY
PREST:	MOV	P1,#0FFH	;休止符：不發聲、燈全滅
PBODY:	MOV	A,R1
	DEC	A
	JZ	PTAIL		;只有一個單位就直接走尾巴
	MOV	R6,A
P10:	MOV	R7,#10		;一個單位 = 10ms
	CALL	DELAY
	DJNZ	R6,P10
PTAIL:	MOV	R7,#4		;最後一個單位：4ms 有聲
	CALL	DELAY
	CLR	TR0		;收聲
	CLR	TF0
	SETB	Buzzer
	MOV	P1,#0FFH
	MOV	R7,#6		;          6ms 靜音，連續同音才分得開
	CALL	DELAY
	RET
;==== 延遲 R7 毫秒(Timer1 輪詢) ======================
; 不能用 DJNZ 數迴圈 —— 蜂鳴器的中斷很密集會把迴圈拖慢，硬體計時器才準。
DELAY:	MOV	TH1,#HIGH(65536-1000)
	MOV	TL1,#LOW(65536-1000)
	CLR	TF1
	SETB	TR1
DLY1:	JNB	TF1,$		;等這 1ms 走完
	CLR	TF1
	MOV	TH1,#HIGH(65536-1000)	;模式 1 不會自動重載
	MOV	TL1,#LOW(65536-1000)
	DJNZ	R7,DLY1
	CLR	TR1
	RET
;==== Timer0 中斷：翻轉蜂鳴器腳位 ====================
; 沒有動到 A 和 PSW，所以不必 PUSH。
T0ISR:	MOV	TH0,RELD_H	;模式 1 不會自動重載
	MOV	TL0,RELD_L
	CPL	Buzzer
	RETI
;==== 音高表：Timer0 的重載值 ========================
; 12MHz → 1 個計數 = 1us，每次中斷翻轉一次，所以數的是半週期：
;   重載值 = 65536 - 500000/頻率 + 9   (+9 補中斷反應吃掉的機械週期)
