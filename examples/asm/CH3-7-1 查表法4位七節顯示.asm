SEGP	EQU	P0
SCANP	EQU	P2
DIGITS	EQU	4
SCAN_TIME	EQU	8
START:	MOV	R4,#0
LOOP0:	MOV	SCANP,#0FFH
	MOV	DPTR,#DISP_DATA
	MOV	A,R4
	MOVC	A,@A+DPTR
	MOV	DPTR,#CA_CODE
	MOVC	A,@A+DPTR
	MOV	SEGP,A
	MOV	DPTR,#SCAN_CODE
	MOV	A,R4
	MOVC	A,@A+DPTR
	MOV	SCANP,A
	MOV	R7,#SCAN_TIME
	CALL	DELAYx500us
	INC	R4
	CJNE	R4,#DIGITS,LOOP0
	JMP	START
DELAYx500us:
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
DISP_DATA:
	DB	8,0,5,1
CA_CODE:
	DB	00000011B
	DB	10011111B
	DB	00100101B
	DB	00001101B
	DB	10011001B
	DB	01001001B
	DB	01000001B
	DB	00011111B
	DB	00000001B
	DB	00001001B
SCAN_CODE:
	DB	01111111B
	DB	10111111B
	DB	11011111B
	DB	11101111B
	DB	11110111B
	DB	11111011B
	DB	11111101B
	DB	11111110B
	END
