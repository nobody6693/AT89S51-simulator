;==== 2-7-6 選擇式控制電路：指撥開關選 4 種燈號 ==============================
;
; 電路：主板就夠用，不用接線
;   P0.1 P0.0 → 指撥開關 SW1 的第 2、1 位（撥 ON 讀 0）；P1 → 8 顆 LED（低態亮）
;
; 原理：讀 P0 整個位元組，反相之後 ON 的位元變 1，值就是 0~3 的狀態號碼：
;   0 → 全暗；1（只撥第 1 位）→ 低四顆亮；2（只撥第 2 位）→ 高四顆亮；
;   3（兩位都撥）→ 全部每 0.1 秒閃一次。閃爍用 30H 當記憶，每輪反相一次再輸出。
;   判斷方式是「反相後減 1、減 2、減 3 看是不是 0」，每次重新讀一次 P0 再減，
;   因為 SUBB 會動到 A。
;
; 時序：DELAY100ms = 250 × 2us × 200 = 0.1 秒
;
; 流程：P0 寫 0FFH 當輸入 → LED 全暗、30H = 0 → 迴圈讀開關、算狀態、跳到 S0~S3 → 回迴圈
SW     EQU  P0          ;設定 SW 開關位址
LED    EQU  P1          ;設定 LED 位址
;==== 主程式 =========================================
       ORG  0           ;程式從 0 位址開始
START: MOV  SW, #0FFh   ;規劃 SW 為輸入埠
       MOV  LED,#0FFH   ;關閉 LED
       MOV  30H,#0      ;設置暫存區初值
LOOP:  MOV  A,SW        ;讀取指撥開關
       CPL  A           ;將 A 反相
       JZ   S0          ;判斷狀態 0
       SUBB A,#1        ;A 減 1
       JZ   S1          ;判斷狀態 1
       MOV  A,SW        ;讀取指撥開關
       CPL  A           ;將 A 反相
       SUBB A,#2        ;A 減 2
       JZ   S2          ;判斷狀態 2
       MOV  A,SW        ;讀取指撥開關
       CPL  A           ;將 A 反相
       SUBB A,#3        ;A 減 3
       JZ   S3          ;判斷狀態 3
       JMP  LOOP        ;重新判斷開關
S0:    MOV  LED,#0FFH   ;關閉 LED
       JMP  LOOP        ;重新判斷開關
S1:    MOV  LED,#0F0H   ;高 4 位元不亮，低 4 位元亮
       JMP  LOOP        ;重新判斷開關
S2:    MOV  LED,#0FH    ;高 4 位元亮，低 4 位元不亮
       JMP  LOOP        ;重新判斷開關
S3:    MOV  LED,30H     ;驅動 LED
       MOV  A,30H       ;載入暫存值
       CPL  A           ;反相
       MOV  30H,A       ;存回暫存區
       CALL DELAY100ms  ;延時 0.1 秒
       JMP  LOOP        ;重新判斷開關
;==== 延時副程式(0.1 秒) ================================
DELAY100ms:
       MOV  R7, #200    ;R7 暫存器載入 200 次數
D1:    MOV  R6, #250    ;R6 暫存器載入 250 次數
       DJNZ R6, $       ;本列執行 R6 次
       DJNZ R7, D1      ;D1 迴圈執行 R7 次
       RET              ;返回主程式
       END              ;結束程式
