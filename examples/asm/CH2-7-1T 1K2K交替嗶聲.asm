Switch	EQU	P0.0
Buzzer	EQU	P3.7
	ORG	0
START:	SETB	Switch
	SETB	Buzzer
	JNB	Switch,BOTH
	JMP	START
BOTH:	MOV	R0,#100
	MOV	R1,#250
	CALL	BEEP_N
	CALL	DELAY100ms
	MOV	R0,#200
	MOV	R1,#125
	CALL	BEEP_N
	CALL	DELAY100ms
	JMP	START
BEEP_N:	CLR	Buzzer
	MOV	A,R1
	MOV	R7,A
	DJNZ	R7,$
	SETB	Buzzer
	MOV	A,R1
	MOV	R7,A
	DJNZ	R7,$
	DJNZ	R0,BEEP_N
	RET
DELAY100ms:
	MOV	R7,#200
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
	END
