;==== 5-4-1 串列埠轉並列式輸入埠：74165 讀指撥開關，顯示在 P1 的 LED ====
;
; 電路：74165 接在 P3.0~P3.2（模擬器載入範例時會自動接上，開關在板子下方的「串列埠外接」）
;   74165 第 9 腳 out(QH)     → P3.0 (RxD)   串列資料進 8051
;   74165 第 2 腳 clock       → P3.1 (TxD)   8051 送出的移位脈波
;   74165 第 1 腳 shift/load  → P3.2         負脈波 = 載入 A~H
;   74165 第 15 腳 clock inhibit 接地、A~H 接指撥開關（10K 上拉，ON = 0、OFF = 1）
;
; 原理：串列埠 Mode 0 是同步移位，TxD 送脈波、RxD 收資料，每個機械週期一位（OSC/12，12MHz = 1us）。
;   REN=1 且 RI=0 就開始收，8 個脈波收滿、RI 變 1，所以「清 RI」就是「開始收」的動作。
;   Mode 0 先收到的放 D0，而 74165 最先移出來的是 H，因此 H → D0(P1.0)、A → D7(P1.7)。
;   開關 ON 讀到 0，LED 又是低態亮，所以開關 ON 對應的 LED 就會亮。
;
; 流程：P3.2 給負脈波載入開關 → 清 RI 開始收 → 等 RI=1 → SBUF 送到 P1 → 再來一次
;   一圈 = 2+1+1+2+2+收 8us+2+2+2 約 22us，撥開關幾乎是立刻反應。
;
LED	EQU	P1		;LED 輸出埠
;========================================
	ORG	0		;程式從 0 位址開始
START:	MOV	SCON,#11H	;設定為 mode 0、REN=1、RI=1（RI 先設 1，免得還沒載入就開始收）
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====0====0====0====1====0====0====0====1===
LOOP:	CLR	P3.2		;輸出負脈波
	NOP			;擴大負脈波寬度
	NOP			;擴大負脈波寬度
	SETB	P3.2		;恢復高態
	CLR	RI		;清除 RI 旗標（這一清，8051 就開始送 8 個移位脈波）
	JNB	RI,$		;等待 RI 串列輸入中斷
	MOV	LED,SBUF	;直到將串列輸入資料輸出到 LED
	JMP	LOOP		;跳至 LOOP 形成一個迴圈
	END
