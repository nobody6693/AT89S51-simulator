;==== 2-7-5 切換式控制電路：同一顆按鈕按一下亮、再按一下暗 ===================
;
; 電路：主板就夠用，不用接線
;   P2.0 → 按鈕 PB3（按下接地讀 0）；P1.7~P1.0 → 8 顆 LED（低態亮）
;
; 原理：A 記住目前狀態（0FFH 全暗、00H 全亮），每按一次就 CPL A 反相再輸出，
;   所以同一顆鍵會在亮、暗之間切換。
;   按下後先延時 0.05 秒（消彈跳），再等放開才切換，按住不放不會一直閃。
;
; 流程：P2.0 寫 1 當輸入 → LED 全暗、A = 0FFH → 等按鈕 → 延時、等放開 → A 反相 → 輸出
PB     EQU  P2.0       ;設定 PB 開關位址
LED    EQU  P1         ;設定 LED 位址
;==== 主程式 =========================================
       ORG  0          ;程式從 0 位址開始
START: SETB PB         ;規劃 PB 為輸入埠
       MOV  LED,#0FFH  ;關閉 LED
       MOV  A,#0FFH    ;設定 A 之初值
LOOP:  JNB  PB,TOGGLE  ;判斷 PB 開關
       JMP  LOOP       ;重新判斷開關
TOGGLE: CALL DELAY50ms ;延時 0.05 秒
       JNB  PB,TOGGLE  ;判斷 PB 開關放開沒？
       CPL  A          ;改變 A 之狀態
       MOV  LED,A      ;驅動 LED
       JMP  LOOP       ;重新判斷開關
;==== 延時副程式(0.05 秒) ==============================
DELAY50ms:
       MOV  R7, #100   ;R7 暫存器載入 100 次數
D1:    MOV  R6, #250   ;R6 暫存器載入 250 次數
       DJNZ R6, $      ;本列執行 R6 次
       DJNZ R7, D1     ;D1 迴圈執行 R7 次
       RET             ;返回主程式
       END             ;結束程式
