;==== 2-7-7 延時式控制電路：按一下，10 秒後開燈，亮 60 秒自動關 ================
;
; 電路：主板就夠用，不用接線
;   P2.0 → 按鈕 PB3（按下讀 0）；P1 → 8 顆 LED（低態亮）
;
; 原理：像樓梯間的延時開關。按下後先等 T_1 秒才開燈，亮 T_2 秒後自動關，再回去等按鈕。
;   DELAY 副程式用 R4 傳秒數：內三層迴圈 250 × 2us × 200 × 10 = 1 秒，外層 R4 次。
;   R4 是 8 位元，最多 255 秒。
;
; 流程：P2.0 寫 1 當輸入 → LED 全暗 → 等按鈕 → 延時 10 秒 → 開燈 → 延時 60 秒 → 關燈 → 回去等
PB     EQU  P2.0       ;設定 PB 開關位址
LED    EQU  P1         ;設定 LED 位址
T_1    EQU  10         ;設定第一段延時時間(秒)
T_2    EQU  60         ;設定第二段延時時間(秒)
;==== 主程式 =========================================
       ORG  0          ;程式從 0 位址開始
START: SETB PB         ;規劃 PB 為輸入埠
       MOV  LED,#0FFH  ;關閉 LED
LOOP:  JNB  PB,ON      ;判斷 PB 開關
       JMP  LOOP       ;重新判斷開關
ON:    MOV  R4,#T_1    ;設定開啟延時時間
       CALL DELAY      ;呼叫延時副程式
       MOV  LED,#0     ;開啟 LED
       MOV  R4,#T_2    ;設定關閉延時時間
       CALL DELAY      ;呼叫延時副程式
       MOV  LED,#0FFH  ;關閉 LED
       JMP  LOOP       ;重新判斷開關
;==== 延時副程式(R4 傳入延時秒數) ==========================
DELAY: MOV  R5, #10    ;R5 暫存器載入 10 次數/1 秒
D0:    MOV  R7, #200   ;R7 暫存器載入 200 次數 0.1 秒
D1:    MOV  R6, #250   ;R6 暫存器載入 250 次數
       DJNZ R6, $      ;本列執行 R6 次
       DJNZ R7, D1     ;D1 迴圈執行 R7 次
       DJNZ R5, D0     ;D0 迴圈執行 R5 次
       DJNZ R4, DELAY  ;DELAY 迴圈執行 R4 次
       RET             ;返回主程式
       END             ;結束程式
