LED	EQU	P1
Buzzer	EQU	P3.7
	ORG	0
	SETB	Buzzer
START:	MOV	A,#0FEH
LEFT:	MOV	R0,#7
	MOV	LED,A
LOOPL:	CALL	DELAY100ms
	RL	A
	ORL	A,#1
	MOV	LED,A
	DJNZ	R0,LOOPL
	CALL	DELAY100ms
	MOV	R1,#2
	CALL	BEEP_N
RIGHT:	MOV	R0,#7
	MOV	LED,A
LOOPR:	CALL	DELAY100ms
	RR	A
	ORL	A,#10000000B
	MOV	LED,A
	DJNZ	R0,LOOPR
	CALL	DELAY100ms
	MOV	R1,#1
	CALL	BEEP_N
	JMP	START
BEEP_N:	MOV	R0,#100
BEEP1:	CLR	Buzzer
	MOV	R7,#250
	DJNZ	R7,$
	SETB	Buzzer
	MOV	R7,#250
	DJNZ	R7,$
	DJNZ	R0,BEEP1
	CALL	DELAY100ms
	DJNZ	R1,BEEP_N
	RET
DELAY100ms:
	MOV	R7,#200
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
	END
