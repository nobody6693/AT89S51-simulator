SEGP	EQU	P0
SCANP	EQU	P2
BUZZER	EQU	P3.7
SEC_COUNT	EQU	20
T0X	EQU	50000
T1X	EQU	5000
M1TH0	EQU	50H
M1TL0	EQU	51H
M1TH1	EQU	52H
M1TL1	EQU	53H
COUNTS	EQU	54H
DIG0	EQU	55H
DIG1	EQU	56H
SCANCODE	EQU	57H
	ORG	0
	JMP	START
	ORG	0BH
	JMP	TIMER
	ORG	1BH
	JMP	SCAN
START:	MOV	SP,#30H
	MOV	IE,#10001010B
	MOV	TMOD,#00010001B
	MOV	COUNTS,#0
	MOV	DIG0,#0
	MOV	DIG1,#0
	MOV	SCANCODE,#1
	MOV	M1TH0,#HIGH(-T0X)
	MOV	TH0,M1TH0
	MOV	M1TL0,#LOW(-T0X)
	MOV	TL0,M1TL0
	MOV	M1TH1,#HIGH(-T1X)
	MOV	TH1,M1TH1
	MOV	M1TL1,#LOW(-T1X)
	MOV	TL1,M1TL1
	SETB	TR0
	SETB	TR1
	JMP	$
TIMER:	MOV	TH0,M1TH0
	MOV	TL0,M1TL0
	INC	COUNTS
	MOV	A,COUNTS
	CJNE	A,#SEC_COUNT,T0_0
	MOV	COUNTS,#0
	INC	DIG0
	MOV	A,DIG0
	CJNE	A,#10,T0_0
	MOV	DIG0,#0
	INC	DIG1
	MOV	A,DIG1
	CJNE	A,#6,T0_0
	MOV	DIG1,#0
	MOV	R4,#2
	CALL	BEEP
T0_0:	RETI
SCAN:	MOV	TH1,M1TH1
	MOV	TL1,M1TL1
	MOV	SCANP,#0FFH
	MOV	A,SCANCODE
	CJNE	A,#1,SCAN_1
	MOV	A,DIG0
	MOV	DPTR,#CA_CODE
	MOVC	A,@A+DPTR
	MOV	SEGP,A
	MOV	A,SCANCODE
	CPL	A
	MOV	SCANP,A
	INC	SCANCODE
	JMP	T1_0
SCAN_1:	MOV	A,DIG1
	MOV	DPTR,#CA_CODE
	MOVC	A,@A+DPTR
	MOV	SEGP,A
	MOV	A,SCANCODE
	CPL	A
	MOV	SCANP,A
	MOV	SCANCODE,#1
T1_0:	RETI
DELAY500us:
D0:	MOV	R7,#250
	DJNZ	R7,$
	DJNZ	R5,D0
	RET
BEEP:	MOV	A,R4
BP1:	MOV	R3,#100
BP0:	CLR	BUZZER
	MOV	R5,#1
	CALL	DELAY500us
	SETB	BUZZER
	MOV	R5,#1
	CALL	DELAY500us
	DJNZ	R3,BP0
	MOV	R5,#200
	CALL	DELAY500us
	DJNZ	R4,BP1
	RET
CA_CODE:
	DB	00000011B
	DB	10011111B
	DB	00100101B
	DB	00001101B
	DB	10011001B
	DB	01001001B
	DB	01000001B
	DB	00011111B
	DB	00000001B
	DB	00001001B
	END
