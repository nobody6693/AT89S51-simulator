Switch	EQU	P0.0
Buzzer	EQU	P3.7
	ORG	0
START:	SETB	Switch
	SETB	Buzzer
	JNB	Switch,Beep
	JMP	START
Beep:	MOV	R0,#100
LOOP:	CLR	Buzzer
	CALL	DELAY500us
	SETB	Buzzer
	CALL	DELAY500us
	DJNZ	R0,LOOP
	CALL	DELAY100ms
	JMP	START
DELAY500us:
	MOV	R7,#250
	DJNZ	R7,$
	RET
DELAY100ms:
	MOV	R7,#200
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
	END
