LED	EQU	P1
	ORG	0
START:	MOV	A,#0FEH
LEFT:	MOV	R0,#7
	MOV	LED,A
LOOPL:	CALL	DELAY100ms
	RL	A
	ORL	A,#1
	MOV	LED,A
	DJNZ	R0,LOOPL
	CALL	DELAY100ms
RIGHT:	MOV	R0,#7
	MOV	LED,A
LOOPR:	CALL	DELAY100ms
	RR	A
	ORL	A,#10000000B
	MOV	LED,A
	DJNZ	R0,LOOPR
	CALL	DELAY100ms
	JMP	START
DELAY100ms:
	MOV	R7,#200
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
	END
