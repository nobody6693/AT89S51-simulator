;==== 5-4-5 思考題：PC 下命令，8051 的 LED 照著做 ====
;
; 思考題要求：
; 讓個人電腦指揮 8051 工作，例如 PC 送出 1 時，LED 進行 8 燈閃爍；
; PC 送出 2 時，LED 進行單燈左移，以此類推。
;   這裡接著排：3 = 單燈右移、0 = 全滅。送數字本身（01H）或字元 '1'（31H）都可以。
;
; 怎麼從範例（CH5-4-5 PC與8051連線）改成這一題：
; 1. 串列埠設定不動（Mode 1、4800bps），PC 那邊也不用改。
; 2. 收資料改用中斷：LED 動畫要用延時，主程式不能卡在 JNB RI,$ 等命令。
;    中斷副程式把命令記到 CMD，設旗標 NEW，主程式下一輪就換動畫。
; 3. 主迴圈不再讀開關，改成每 0.1 秒照 CMD 算下一個 LED 樣板。
; 4. ANL A,#0FH 只留低 4 位：'1' = 31H 變成 1，數字 1 還是 1，兩種送法都通。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
LED	EQU	P1		;LED 輸出埠
CMD	EQU	30H		;【加】PC 下的命令
NEW	BIT	00H		;【加】1 = 剛收到新命令，動畫要重新開始
;========================================
	ORG	0		;程式從 0 位址開始
	JMP	START		;【加】跳過中斷向量
	ORG	23H		;【加】串列埠中斷向量
	JMP	S_INT		;【加】
START:	MOV	SP,#40H		;【加】堆疊搬離暫存器庫與 CMD
	MOV	SCON,#01010000B	;設定為 mode 1、REN=1、RI=0
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====0====1====0====1====0====0====0====0===
	; 產生鮑率
	MOV	TMOD,#20H	;將 Timer 1 設定 Mode 2（8 位元自動重載）
	ORL	PCON,#80H	;將 SMOD 設定為 1
	MOV	TH1,#0F3H	;鮑率設定為 4800bps
	SETB	TR1		;啟動 Timer 1
	MOV	CMD,#0		;【加】還沒收到命令：全滅
	CLR	NEW		;【加】
	MOV	IE,#10010000B	;【加】EA + ES：開串列埠中斷
	MOV	A,#0FFH		;【加】LED 樣板，先全滅
LOOP:	MOV	LED,A		;【改】輸出樣板
	MOV	R5,#200		;【加】200 × 0.5ms = 0.1 秒
	CALL	DELAY500us	;【加】停 0.1 秒
	MOV	R2,CMD		;【加】看現在的命令
	JBC	NEW,RESTART	;【加】剛換命令：動畫從頭開始
	CJNE	R2,#1,TRY2	;【加】
	CPL	A		;【加】命令 1：8 燈閃爍，全部反相
	JMP	LOOP		;【加】
TRY2:	CJNE	R2,#2,TRY3	;【加】
	RL	A		;【加】命令 2：單燈左移
	JMP	LOOP		;【加】
TRY3:	CJNE	R2,#3,LOOP	;【加】命令 0 或其他：維持全滅
	RR	A		;【加】命令 3：單燈右移
	JMP	LOOP		;【改】跳至 LOOP 形成一個迴圈
;=== 換命令：算出動畫的第一個樣板 ======================
RESTART:	MOV	A,#00H		;【加】命令 1：先全亮
	CJNE	R2,#1,R_2	;【加】
	JMP	LOOP		;【加】
R_2:	MOV	A,#0FEH		;【加】命令 2、3：只亮一顆
	CJNE	R2,#2,R_3	;【加】
	JMP	LOOP		;【加】
R_3:	CJNE	R2,#3,R_OFF	;【加】
	JMP	LOOP		;【加】
R_OFF:	MOV	A,#0FFH		;【加】其他命令：全滅
	JMP	LOOP		;【加】
;=== 串列埠中斷：收到 PC 的命令 ========================
S_INT:	JNB	RI,S_END	;【加】只處理接收（這題沒有傳出）
	PUSH	ACC		;【加】主程式的 A 是 LED 樣板，要保住
	MOV	A,SBUF		;【加】讀 PC 傳來的資料
	ANL	A,#0FH		;【加】'1'(31H) 與 1 都當成 1
	MOV	CMD,A		;【加】記下命令
	SETB	NEW		;【加】通知主程式換動畫
	POP	ACC		;【加】還原
	CLR	RI		;【加】清除 RI 旗標，不清會一直中斷
S_END:	RETI			;【加】返回主程式
;==== 延時副程式：R5 × 0.5ms ============================
DELAY500us:
D0:	MOV	R7,#250		;內迴圈 250 × 2us = 0.5ms
	DJNZ	R7,$		;2 個機械週期 × 250 次
	DJNZ	R5,D0		;外迴圈 R5 次
	RET			;返回呼叫處
	END
