;==== 2-7-7 思考題：開燈時間延長為 1 小時 ====
;
; 思考題要求：
; LED 亮的時間從 60 秒改成 1 小時（3600 秒）。
;
; 怎麼從範例（CH2-7-7 延時式控制電路）改成這一題：
; 1. 問題：DELAY 的秒數放在 R4，8 位元最多 255 秒，裝不下 3600。
; 2. 解法：一次延時 60 秒（1 分鐘），外面再用 R3 數 60 次，60 分鐘 = 1 小時。
; 3. 常數：T_2 改成 T_MIN（60 秒 = 1 分鐘）和 N_MIN（60 次）。
; 4. 開燈之後：原本 MOV R4,#T_2 → CALL DELAY 一次，改成 R3 = N_MIN，
;    迴圈裡每次 R4 = T_MIN、CALL DELAY，DJNZ R3 數滿 60 次才關燈。
;    模擬器要等真的一小時才會關燈，想快點看結果可以暫時把 N_MIN 改小。
; 其餘一行都沒動，跟範例一樣。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
PB     EQU  P2.0       ;設定 PB 開關位址
LED    EQU  P1         ;設定 LED 位址
T_1    EQU  10         ;設定第一段延時時間(秒)
T_MIN  EQU  60         ;【改】T_2 → T_MIN：一分鐘 = 60 秒
N_MIN  EQU  60         ;【加】點亮時間 = 60 分鐘 = 1 小時
;==== 主程式 =========================================
       ORG  0          ;程式從 0 位址開始
START: SETB PB         ;規劃 PB 為輸入埠
       MOV  LED,#0FFH  ;關閉 LED
LOOP:  JNB  PB,ON      ;判斷 PB 開關
       JMP  LOOP       ;重新判斷開關
ON:    MOV  R4,#T_1    ;設定開啟延時時間
       CALL DELAY      ;呼叫延時副程式
       MOV  LED,#0     ;開啟 LED
       MOV  R3,#N_MIN  ;【加】點亮時間設為 60 分鐘
HOLD:  MOV  R4,#T_MIN  ;【改】每次延時 1 分鐘（原本一次延時 T_2 秒）
       CALL DELAY      ;呼叫延時副程式
       DJNZ R3,HOLD    ;【加】R3 次數未到就繼續點亮
       MOV  LED,#0FFH  ;關閉 LED
       JMP  LOOP       ;重新判斷開關
;==== 延時副程式(R4 傳入延時秒數) ==========================
DELAY: MOV  R5, #10    ;R5 暫存器載入 10 次數/1 秒
D0:    MOV  R7, #200   ;R7 暫存器載入 200 次數 0.1 秒
D1:    MOV  R6, #250   ;R6 暫存器載入 250 次數
       DJNZ R6, $      ;本列執行 R6 次
       DJNZ R7, D1     ;D1 迴圈執行 R7 次
       DJNZ R5, D0     ;D0 迴圈執行 R5 次
       DJNZ R4, DELAY  ;DELAY 迴圈執行 R4 次
       RET             ;返回主程式
       END             ;結束程式
