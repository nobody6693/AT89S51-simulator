;==== 5-4-2 思考題：74164 上的 8 顆 LED 單燈左移 ====
;
; 思考題要求：
; 請利用 74164 與 8051 串列埠，讓連接於 74164 的 8 個 LED 呈現「單燈左移」的動態展示。
;
; 怎麼從範例（CH5-4-2 74164並列輸出）改成這一題：
; 1. 要傳的資料不再讀開關，改成樣板 11111110B（低態亮，只亮一顆），每送一次 RL A 一次。
; 2. 範例一送完就送下一筆，太快看不出動作；改成主程式每 0.1 秒送一筆，
;    所以 MOV SBUF 從中斷副程式搬回主程式，中斷副程式只剩 CLR TI。
; 3. 加上延時副程式（跟第 4 章 CH4-7-1 同一支）。
;
; 「左移」照課本前幾章的用法：RL A，亮的那顆由 D0 往 D7 走，跟主板 P1 的左移範例走法一樣。
;   74164 電路板上 DS1~DS8 就是 D0~D7，所以會從 DS1 一路亮到 DS8 再回到 DS1。
; 電路、接線與原理都跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】【加】標出來。
;
;========================================
	ORG	0		;程式從 0 位址開始
	JMP	START		;主程式跳至 START
	ORG	23H		;串列埠中斷向量
	JMP	S_INT		;跳至串列埠中斷副程式
START:	MOV	SCON,#0H	;設定為 mode 0、REN=0、RI=0
;====b7===b6===b5===b4===b3===b2===b1===b0===
;===SM0==SM1==SM2==REN==TB8==RB8===TI===RI===
;=====0====0====0====0====0====0====0====0===
	MOV	IE,#10010000B	;啟用串列埠中斷
	MOV	A,#0FEH		;【改】樣板 11111110：亮 D0 那一顆（DS1）
LOOP:	MOV	SBUF,A		;將所要傳出資料放入 SBUF
	MOV	R5,#200		;【加】200 × 0.5ms = 0.1 秒
	CALL	DELAY500us	;【加】停 0.1 秒讓眼睛看得到
	RL	A		;【加】左旋：亮的那顆往下一位走
	JMP	LOOP		;【改】再送下一筆
;=== 串列埠輸出中斷副程式 ======================
S_INT:	CLR	TI		;清除傳出中斷旗標（【改】資料改由主程式送，這裡只清旗標）
	RETI			;返回主程式
;==== 延時副程式：R5 × 0.5ms ============================
DELAY500us:
D0:	MOV	R7,#250		;內迴圈 250 × 2us = 0.5ms
	DJNZ	R7,$		;2 個機械週期 × 250 次
	DJNZ	R5,D0		;外迴圈 R5 次
	RET			;返回呼叫處
	END
