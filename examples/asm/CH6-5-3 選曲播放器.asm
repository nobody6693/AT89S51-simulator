;==== PLAY：播歌副程式（音調表位址在 60H、61H，節拍表位址在 62H、63H）======
PLAY:	MOV	PLAY_INDEX, #0	;從頭開始播放
	; === 讀取歌曲之音調 =================
NEXT:	MOV	A,PLAY_INDEX	;載入播音指標
	MOV	DPH, T_ADDR_H	;載入音調表位址之高 8 位元
	MOV	DPL, T_ADDR_L	;載入音調表位址之低 8 位元
	MOVC	A,@A+DPTR	;讀取音調（音碼）
	CJNE	A,#ENDING,TRANSFER	;不是結束符號就去發聲
	ORL	BUZZER, #80H	;播完了：關閉蜂鳴器（防燙）
	JMP	EXIT0		;結束播歌
	; === 音調轉換計數量 =================
TRANSFER:	RL	A		;取碼指標等於音碼乘 2
	MOV	R1,A		;暫存取碼指標
	MOV	DPTR, #T_BASE	;指向音階表
	MOVC	A,@A+DPTR	;讀取計時量之高 8 位元
	MOV	M1_TH, A	;存入計時量變數（中斷重載要用）
	MOV	TH0, M1_TH	;填入計時量之高 8 位元
	MOV	A,R1		;取回取碼指標
	INC	A		;下個位址 = 低 8 位元
	MOVC	A,@A+DPTR	;讀取計時量之低 8 位元
	MOV	M1_TL, A	;存入計時量變數
	MOV	TL0, M1_TL	;填入計時量之低 8 位元
	MOV	A,R1		;【補】取回取碼指標：休止符（音碼 0）的指標也是 0
	JZ	GET_BEAT	;【補】休止符不啟動計時器，直接去讀節拍
	SETB	TR0		;啟動計時器（開始播音）
	; === 讀取節拍 ======================
GET_BEAT:	MOV	A,PLAY_INDEX	;載入播音指標
	MOV	DPH, B_ADDR_H	;載入節拍表位址之高 8 位元
	MOV	DPL, B_ADDR_L	;載入節拍表位址之低 8 位元
	MOVC	A,@A+DPTR	;讀取節拍（幾個 1/8 拍）
	MOV	52H,A		;指定延時參數
	;=== 62500us（1/8 拍）× 52H 的延時，直接寫在副程式裡 ===
BEAT:	MOV	51H, #124	;2us
BE0:	MOV	50H, #250	;2us
	DJNZ	50H, $		;2us × 250 = 500us
	DJNZ	51H, BE0	;(2+500+2) × 124 = 62496us
	DJNZ	52H, BEAT	;(62496+4) × 52H us
	CLR	TR0		;停止計時器（停止播音）
	INC	PLAY_INDEX	;播音指標加 1
	JMP	NEXT		;播放下一個音
EXIT0:	RET		;返回
;==== TONE：Timer 0 中斷，每半週期翻轉一次蜂鳴器 ==========================
TONE:	MOV	TH0, M1_TH	;填入計時量之高 8 位元（Mode 1 不會自動重載）
	MOV	TL0, M1_TL	;填入計時量之低 8 位元
	XRL	BUZZER, #80H	;切換蜂鳴器：只把 P3.7 反相，P3 其他腳不動
	RETI		;返回
