;==== 6-5-3 選曲播放器：P2.0~P2.7 碰地，點播 8 首歌 ====
;
; 電路：主板就夠用，另外一條杜邦線
;   P2.0~P2.7 → 選歌鍵。杜邦線一端插 GND，碰哪一支腳就播哪一首：
;     P2.0 平安夜、P2.1 甜蜜的家庭、P2.2 You are my Sunshine、P2.3 點仔膠、
;     P2.4 西北雨、P2.5 青蚵嫂、P2.6 寄語白雲、P2.7 茉莉花
;     模擬器：先點 GND 排針、再點 P2.x 跳一條線過去，播起來後再點一次 P2.x 拆掉；
;     P2.0、P2.1 也可以直接按主板 PB3、PB4
;   P3.7 → 蜂鳴器（經 PNP 電晶體，寫 0 導通發聲，寫 1 不通電）
;
; 原理：播歌的方法跟 6-5-2 一樣（Timer 0 中斷產生音調、延時迴圈產生節拍，
;   1 = 1/8 拍 = 62.5ms），差別是有 8 首歌，播歌部分寫成副程式 PLAY 共用。
;   參數傳遞：音調表、節拍表的位址都是 16 位元，DPTR 只有一個，
;   所以先把兩個位址放到資料記憶體 60H~63H（T_ADDR_H/L、B_ADDR_H/L），
;   PLAY 要讀哪個表就把那兩個位元組搬回 DPH、DPL。
;   接力賽：JNB 只能往後跳 127 個位元組，SWITCH.5~7 跳不到 S6~S8，
;   所以在 S05 前面放三個 JMP 當中繼站（S06、S07、S08），再跳到真正的 S6~S7~S8。
;
; 流程：
;   1. LOOP 依序檢查 P2.0~P2.7，哪一支是 0 就到對應的 S0x
;   2. S0x 把那首歌的音調表、節拍表位址存進 60H~63H，呼叫 PLAY
;   3. PLAY 從第一個音播到結束符號 100，關掉蜂鳴器後返回，回到 1 等下一次選歌
;   播放當中不看按鍵，一定要播完才能選下一首（這一點就是思考題要改的）。
;
; 休止符（音碼 0）：課本在 T_BASE 填 -10，計時器每 10us 就溢位，蜂鳴器以 3 萬多 Hz 翻轉，
;   耳朵聽不到。可是中斷這麼頻繁，主程式只剩約 1/4 的時間在跑，節拍延時跟著拖成約 4 倍：
;   甜蜜的家庭裡 1 拍（0.5 秒）的休止符會停 2 秒，整首從 51 秒拖成 56 秒。所以補兩行【補】：
;   音碼是 0 就不啟動計時器，休止符真的安靜、長度也跟節拍表一樣。
;
; 跟課本不一樣的地方：
;   - 課本把每個表各放在一個節段（SEGMENT / RSEG），這個模擬器的組譯器不認得節段敘述，
;     所以拿掉，表格改放到程式後面；指令一個都沒改。
;   - 課本的歌譜表有五處印錯，照歌譜修正（表格那一行註解寫【修】）：
;     平安夜「All is calm」印成 2,22,7（應為兩個高音 Re 22,22）；
;     甜蜜的家庭第 2 行 3,1,2 後面少逗號（組譯會錯）；
;     You are my Sunshine 第 1 行的 33 不是音（應為 3），第 4 行節拍少一個，
;     最後一個音會讀到表格外面；
;     茉莉花第 4 行節拍少一個（8,8 應為 8,4,4），從那裡開始後面每個音的節拍都錯一格。
;   - PLAY 補兩行（【補】）讓休止符不啟動計時器，原因見上面「休止符」。
;
SWITCH	EQU	P2		;按鈕開關輸入埠（8 個選歌鍵）
BUZZER	EQU	P3		;蜂鳴器輸出埠（蜂鳴器在 P3.7）
M1_TH	EQU	40H		;計時量暫存區之高 8 位元
M1_TL	EQU	41H		;計時量暫存區之低 8 位元
PLAY_INDEX	EQU	42H		;播音指標
ENDING	EQU	100		;結束符號
T_ADDR_H	EQU	60H		;音調表位址高 8 位元暫存區
T_ADDR_L	EQU	61H		;音調表位址低 8 位元暫存區
B_ADDR_H	EQU	62H		;節拍表位址高 8 位元暫存區
B_ADDR_L	EQU	63H		;節拍表位址低 8 位元暫存區
	ORG	0		;程式從 0 位址開始
	JMP	START		;跳至主程式開始
	ORG	0BH		;Timer 0 中斷向量位址
	JMP	TONE		;跳至 TONE 中斷副程式
START:	MOV	IE, #10000010B	;啟用 Timer 0 中斷（EA + ET0）
	MOV	TMOD, #01H	;設定 Timer 0 為 Mode 1（16 位元計時）
	ORL	BUZZER, #80H	;P3.7 = 1：關閉蜂鳴器（防燙）
	MOV	SWITCH, #0FFH	;規畫為輸入埠（先寫 1 才能讀）
LOOP:	JNB	SWITCH.0, S01	;P2.0 碰地 → 第 1 首歌
	JNB	SWITCH.1, S02	;P2.1 碰地 → 第 2 首歌
	JNB	SWITCH.2, S03	;P2.2 碰地 → 第 3 首歌
	JNB	SWITCH.3, S04	;P2.3 碰地 → 第 4 首歌
	JNB	SWITCH.4, S05	;P2.4 碰地 → 第 5 首歌
	JNB	SWITCH.5, S06	;P2.5 碰地 → 第 6 首歌
	JNB	SWITCH.6, S07	;P2.6 碰地 → 第 7 首歌
	JNB	SWITCH.7, S08	;P2.7 碰地 → 第 8 首歌
	JMP	LOOP		;都沒按：繼續檢查
;==== S01~S8：把那首歌兩個表的位址存到 60H~63H =============================
S01:	MOV	DPTR,#SONG1	;載入第 1 首歌之音調位址
	MOV	T_ADDR_H,DPH	;儲存音調位址之高 8 位元
	MOV	T_ADDR_L,DPL	;儲存音調位址之低 8 位元
	MOV	DPTR,#BEAT1	;載入第 1 首歌之節拍位址
	MOV	B_ADDR_H,DPH	;儲存節拍位址之高 8 位元
	MOV	B_ADDR_L,DPL	;儲存節拍位址之低 8 位元
	JMP	PLAY1		;跳至 PLAY1
