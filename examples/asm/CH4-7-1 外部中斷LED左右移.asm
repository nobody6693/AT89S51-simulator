LED	EQU	P1
BUZZER	EQU	P3.7
PATTERN	EQU	0FH
	ORG	0
	JMP	START
	ORG	03H
	JMP	LEFT
	ORG	13H
	JMP	RIGHT
START:	MOV	SP,#30H
	MOV	IE,#10000101B
	MOV	A,#PATTERN
LOOP0:	MOV	LED,A
	MOV	R5,#200
	CALL	DELAY500us
	CPL	A
	JMP	LOOP0
DELAY500us:
D0:	MOV	R7,#250
	DJNZ	R7,$
	DJNZ	R5,D0
	RET
BEEP:	MOV	A,R4
BP1:	MOV	R3,#100
BP0:	CLR	BUZZER
	MOV	R5,#1
	CALL	DELAY500us
	SETB	BUZZER
	MOV	R5,#1
	CALL	DELAY500us
	DJNZ	R3,BP0
	MOV	R5,#200
	CALL	DELAY500us
	DJNZ	R4,BP1
	RET
LEFT:	PUSH	ACC
	PUSH	PSW
	CLR	RS1
	SETB	RS0
	MOV	R4,#2
	CALL	BEEP
	MOV	A,#0FEH
	MOV	R0,#7
L_OUT:	MOV	LED,A
	MOV	R5,#200
	CALL	DELAY500us
	RL	A
	DJNZ	R0,L_OUT
	POP	PSW
	POP	ACC
	RETI
RIGHT:	PUSH	ACC
	PUSH	PSW
	CLR	RS0
	SETB	RS1
	MOV	R4,#2
	CALL	BEEP
	MOV	A,#07FH
	MOV	R0,#7
R_OUT:	MOV	LED,A
	MOV	R5,#200
	CALL	DELAY500us
	RR	A
	DJNZ	R0,R_OUT
	POP	PSW
	POP	ACC
	RETI
	END
