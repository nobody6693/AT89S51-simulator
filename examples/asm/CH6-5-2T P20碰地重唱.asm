;==== 6-5-2 思考題：生日快樂歌唱完後，等 P2.0 碰到低態才重唱 ====
;
; 思考題要求：
; 在本單元裡，送電後自動播放生日快樂歌，播放完畢後，等待 30 秒，再重新播放。
; 請改為播放完畢後，待 P2.0 碰觸低態時，即重新播放。
;
; 怎麼從範例（CH6-5-2 單曲播放器）改成這一題：
;   1. 唱完時的 CALL DELAY30S 換成 JB P2.0,$：P2.0 還是高態（1）就跳回自己，
;      一直等到 P2.0 碰到地（0）才往下走到 JMP LOOP 重唱。
;      P2.0 開機就是 1（重置後 P2 = 0FFH，準輸入），不用另外寫 1。
;   2. DELAY30S 副程式用不到了，整段刪掉。
;   開機一樣先自動唱一次（題目只改「唱完以後」）。
;
; P2.0 怎麼碰：杜邦線一端插 GND 碰 P2.0；P2.0 剛好也是主板按鈕 PB3，按一下 PB3 就重唱。
;   如果唱完的那一刻 P2.0 還按著，會馬上再唱一次。
; 原理跟範例相同，請先看範例檔頭的說明；改過的地方在程式裡用【改】標出來。
; 電路：比範例多一個重唱鍵 P2.0（杜邦線碰 GND 或按主板 PB3，讀到 0），其他一樣。
;
; ---- 以下是範例檔頭 ----
; 電路：主板就夠用，不用接線
;   P3.7 → 蜂鳴器（經 PNP 電晶體，寫 0 導通發聲，寫 1 不通電）
;
; 原理：計時器產生音調、延時副程式產生節拍。
;   音調：跟 6-5-1 一樣，Timer 0 Mode 1 每半週期中斷一次，TONE 重載計時量並翻轉 P3.7。
;   歌曲用三個表：
;     T_BASE 基本音階表：音碼 n → 計時量（n × 2 就是表裡的位置）
;     SONG1  音調表：簡譜照抄，中音 1~7 就寫 1~7，高音 Do 寫 21；最後放 100 當結束符號
;     BEAT1  節拍表：1 = 1/8 拍（62.5ms），8 = 1 拍（0.5 秒），16 = 2 拍
;   節拍：BEAT 副程式延時 52H × 62500us。內圈 DJNZ 50H 250 次 = 500us，
;     加上前後 4us 共 504us × 124 = 62496us，再加外圈 4us ≈ 62500us。
;
; 流程：
;   1. 播音指標 PLAY 歸零
;   2. 用 PLAY 查音調表；是 100 就關掉蜂鳴器、等 30 秒、回到 1
;   3. 不是 100：音碼 ×2 查 T_BASE，取出計時量填好、啟動 Timer 0 開始發聲
;   4. 用同一個 PLAY 查節拍表，延時那麼多個 1/8 拍，停掉 Timer 0
;   5. PLAY 加 1，回到 2 播下一個音
;   生日快樂歌 25 個音、共 192 個 1/8 拍 = 12 秒，唱完靜音 30 秒。
;
; 跟課本不一樣的地方：課本把三個表各放在一個節段（SEGMENT / RSEG），這個模擬器的組譯器
;   不認得節段敘述，所以拿掉，表格改放到程式後面；指令一個都沒改。
;
BUZZER	EQU	P3		;蜂鳴器輸出埠（蜂鳴器在 P3.7）
M1_TH	EQU	40H		;計時量暫存區之高 8 位元
M1_TL	EQU	41H		;計時量暫存區之低 8 位元
PLAY	EQU	42H		;播音指標：現在播到第幾個音
ENDING	EQU	100		;結束符號
	ORG	0		;程式從 0 位址開始
	JMP	START		;跳至主程式開始
	ORG	0BH		;Timer 0 中斷向量位址
	JMP	TONE		;跳至 TONE 中斷副程式
START:	MOV	IE, #10000010B	;啟用 Timer 0 中斷（EA + ET0）
	MOV	TMOD, #01H	;設定 Timer 0 為 Mode 1（16 位元計時）
LOOP:	MOV	PLAY, #0	;播音指標歸零：從第一個音開始
	ORL	BUZZER, #80H	;P3.7 = 1：關閉蜂鳴器（防燙）
	; === 讀取歌曲之音調 =================
NEXT:	MOV	A,PLAY		;載入播音指標
	MOV	DPTR, #SONG1	;指向歌曲音調表
	MOVC	A,@A+DPTR	;讀取音調（音碼）
	CJNE	A,#ENDING,TRANSFER	;不是結束符號就去發聲
	ORL	BUZZER, #80H	;唱完了：關閉蜂鳴器（防燙）
	JB	P2.0, $		;【改】原本等 30 秒：P2.0 還是 1 就原地等，碰地才往下
	JMP	LOOP		;P2.0 碰到低態：重新演奏
	; === 音調轉換計數量 =================
TRANSFER:	RL	A		;取碼指標等於音碼乘 2
	MOV	R1,A		;暫存取碼指標
	MOV	DPTR, #T_BASE	;指向音階表
	MOVC	A,@A+DPTR	;讀取計時量之高 8 位元
	MOV	M1_TH, A	;存入計時量變數（中斷重載要用）
	MOV	TH0, M1_TH	;填入計時量之高 8 位元
	MOV	A,R1		;取回取碼指標
	INC	A		;下個位址 = 低 8 位元
	MOVC	A,@A+DPTR	;讀取計時量之低 8 位元
	MOV	M1_TL, A	;存入計時量變數
	MOV	TL0, M1_TL	;填入計時量之低 8 位元
	SETB	TR0		;啟動計時器（開始播音）
	; === 讀取節拍 ======================
	MOV	A,PLAY		;載入播音指標
	MOV	DPTR, #BEAT1	;指向歌曲節拍表
	MOVC	A,@A+DPTR	;讀取節拍（幾個 1/8 拍）
	MOV	52H,A		;指定延時參數
	CALL	BEAT		;呼叫節拍副程式
	CLR	TR0		;停止計時器（停止播音）
	INC	PLAY		;播音指標加 1
	JMP	NEXT		;播放下一個音
;==== BEAT：62500us（1/8 拍）× 52H 的延時副程式 ===========================
BEAT:	MOV	51H, #124	;2us
BE0:	MOV	50H, #250	;2us
	DJNZ	50H, $		;2us × 250 = 500us
	DJNZ	51H, BE0	;(2+500+2) × 124 = 62496us
	DJNZ	52H, BEAT	;(62496+4) × 52H us：52H 個 1/8 拍
	RET		;返回
;【改】DELAY30S 用不到了，整段刪掉
;==== TONE：Timer 0 中斷，每半週期翻轉一次蜂鳴器 ==========================
TONE:	MOV	TH0, M1_TH	;填入計時量之高 8 位元（Mode 1 不會自動重載）
	MOV	TL0, M1_TL	;填入計時量之低 8 位元
	XRL	BUZZER, #80H	;切換蜂鳴器：只把 P3.7 反相，P3 其他腳不動
	RETI		;返回
;==== 基本音階表 T_BASE：音碼 n 的計時量放在第 n 個字組（DW 先放高位元組）====
;  計時量 = -(半週期 us)。12MHz 時計時器每 1us 加 1，數到溢位剛好半週期。
;  中音 1~7 = 1~7，低音 Do~Si = 11~17，高音 Do~Si = 21~27，中音升記號 31、32、34~36；
;  沒用到的填 -1（課本說是「靜音」）
T_BASE:	;0	1	2	3	4
	DW	-1,	-956,	-852,	-759,	-716	;-、中音 Do Re Mi Fa
	;5	6	7	8	9
	DW	-638,	-568,	-506,	-1,	-1	;中音 So La Si
	;10	11	12	13	14
	DW	-1,	-1908,	-1701,	-1515,	-1433	;低音 Do Re Mi Fa
	;15	16	17	18	19
	DW	-1276,	-1136,	-1012,	-1,	-1	;低音 So La Si
	;20	21	22	23	24
	DW	-1,	-478,	-426,	-379,	-358	;高音 Do Re Mi Fa
	;25	26	27	28	29
	DW	-319,	-284,	-253,	-1,	-1	;高音 So La Si
	;30	31	32	33	34
	DW	-1,	-903,	-804,	-1,	-676	;中音 Do# Re# - Fa#
	;35	36
	DW	-602,	-526			;中音 So# La#
;==== SONG1 生日快樂歌音調表（簡譜照抄，高音 Do = 21，100 = 結束）==========
SONG1:
	DB	1,1,2,1, 4,3, 1,1,2,1, 5,4	;祝你生日快樂 ×2
	DB	1,1,21,6, 4,3,2, 7,7,6,4, 5,4, 100	;祝你生日快樂（高音）、祝你生日快樂
;==== BEAT1 生日快樂歌節拍表（1 = 1/8 拍，8 = 1 拍 = 0.5 秒）==============
BEAT1:
