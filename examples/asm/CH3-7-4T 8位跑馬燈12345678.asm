SEGP	EQU	P0
SCANP	EQU	P2
DIGITS	EQU	8
SCAN_TIME	EQU	2
SCAN_COUNT	EQU	100
START:	MOV	R2,#0
LOOP2:	MOV	R5,#SCAN_COUNT
LOOP1:	MOV	R4,#0
LOOP0:	MOV	SCANP,#0FFH
	MOV	DPTR,#DISP_DATA
	MOV	A,R4
	MOVC	A,@A+DPTR
	MOV	DPTR,#CA_CODE
	MOVC	A,@A+DPTR
	MOV	SEGP,A
	MOV	A,R4
	ADD	A,R2
	MOV	R3,A
	ANL	A,#0F8H
	JZ	OK
	MOV	A,R3
	SUBB	A,#DIGITS
	MOV	R3,A
OK:	MOV	DPTR,#SCAN_CODE
	MOV	A,R3
	MOVC	A,@A+DPTR
	MOV	SCANP,A
	MOV	R7,#SCAN_TIME
	CALL	DELAYx500us
	INC	R4
	CJNE	R4,#DIGITS,LOOP0
	DJNZ	R5,LOOP1
	INC	R2
	CJNE	R2,#DIGITS,LOOP2
	JMP	START
DELAYx500us:
D1:	MOV	R6,#250
	DJNZ	R6,$
	DJNZ	R7,D1
	RET
DISP_DATA:
	DB	1,2,3,4,5,6,7,8
CA_CODE:
	DB	00000011B
	DB	10011111B
	DB	00100101B
	DB	00001101B
	DB	10011001B
	DB	01001001B
	DB	01000001B
	DB	00011111B
	DB	00000001B
	DB	00001001B
SCAN_CODE:
	DB	01111111B
	DB	10111111B
	DB	11011111B
	DB	11101111B
	DB	11110111B
	DB	11111011B
	DB	11111101B
	DB	11111110B
	END
