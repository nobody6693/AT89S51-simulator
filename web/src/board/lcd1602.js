// 取得字元的 8 列點陣（每列 5 bit，bit4 = 最左）
export function glyphRows(code, cgram) {
  const rows = new Uint8Array(8);
  if (code < 8) { // CGRAM 自訂字元（0–7，8–15 為鏡射）
    for (let r = 0; r < 8; r++) rows[r] = cgram[code * 8 + r] & 0x1F;
    return rows;
  }
  if (code >= 8 && code < 16) return glyphRows(code - 8, cgram);
  if (code < 0x20 || code > 0x7F) { rows.fill(0); return rows; }
  const base = (code - 0x20) * 5;
  for (let r = 0; r < 8; r++) {
    let v = 0;
    for (let c = 0; c < 5; c++) if ((FONT[base + c] >> r) & 1) v |= (0x10 >> c);
    rows[r] = v;
  }
  return rows;
}

const BUSY_CMD = 37, BUSY_CLEAR = 1520; // µs

export class Lcd1602 {
  constructor(sim) {
    this.sim = sim;
    this.ddram = new Uint8Array(0x80);
    this.cgram = new Uint8Array(64);
    this.attached = false; // LCM 模組是否插在 JP2 上（照片中出廠未插）
    this.reset();
    this.log = []; // 最近的命令（除錯用）
    this.bus = sim.bus;
    this.bus.onWrite((port, now, old) => this._onWrite(port, now, old));
    this.bus.addDriver(this);
  }
  reset() {
    this.ddram.fill(0x20); this.cgram.fill(0);
    this.ac = 0; this.cgMode = false;
    this.entryInc = true; this.entryShift = false;
    this.displayOn = false; this.cursorOn = false; this.blinkOn = false;
    this.lines2 = false; this.font10 = false; this.dl8 = true;
    this.shift = 0;
    this.nibbleHigh = true; this.nibble = 0;
    this.busyUntil = 0;
    this.initStage = 0;   // 4-bit 初始化計數
    this.warnings = new Set();
    this.lastE = 1;
    this.readData = 0;
  }
  get busy() { return this.sim.cpu.cycles < this.busyUntil; }

  // 讀取期間驅動 P0
  update(pins, latch) {
    if (!this.attached) return { low: [0, 0, 0, 0], high: [0, 0, 0, 0] };
    const p3 = latch[3];
    const e = (p3 >> 0) & 1, rw = (p3 >> 1) & 1, rs = (p3 >> 2) & 1;
    if (e && rw) {
      let v;
      if (!rs) v = (this.busy ? 0x80 : 0) | (this.ac & 0x7F);
      else v = this._readAtAC();
      if (!this.dl8) { v = this.nibbleHigh ? (v & 0xF0) : ((v << 4) & 0xF0); }
      return { high: [v, 0, 0, 0], low: [(~v) & 0xFF, 0, 0, 0] };
    }
    return { low: [0, 0, 0, 0], high: [0, 0, 0, 0] };
  }

  _onWrite(port, now, old) {
    if (port !== 3) return;
    const e = now & 1, eOld = old & 1;
    if (eOld === 1 && e === 0) {
      // E 下降緣
      const rw = (now >> 1) & 1, rs = (now >> 2) & 1;
      if (!this.attached) { if (rw === 0) this.warnings.add('程式正在對 LCM 寫入，但 LCM 未插上 — 點板子上的 LCM 面板可插上'); return; }
      if (rw === 0) {
        const data = this.bus.pins[0]; // 實際腳位（含指撥開關干擾）
        if (this.bus.latch[0] !== data) this.warnings.add('P0 資料被指撥開關拉低：LCD 收到的資料與程式寫的不同（請把 SW1 全部撥 OFF）');
        this._write(rs, data);
      } else {
        // 讀取結束：資料讀取後 AC 自動移動
        if (rs) { if (this.dl8 || !this.nibbleHigh) this._advance(); if (!this.dl8) this.nibbleHigh = !this.nibbleHigh; }
        else if (!this.dl8) this.nibbleHigh = !this.nibbleHigh;
      }
    }
  }

  _write(rs, byte) {
    if (!this.dl8) {
      // 4-bit 模式：高 nibble 先
      if (this.nibbleHigh) { this.nibble = byte & 0xF0; this.nibbleHigh = false; return; }
      byte = this.nibble | (byte >> 4); this.nibbleHigh = true;
    }
    if (this.busy) this.warnings.add(`在 LCD 忙碌期間寫入（${rs ? '資料' : '命令'} ${hex2(byte)}），真實硬體會忽略此筆寫入`);
    if (rs) this._writeData(byte); else this._command(byte);
    if (this.log.length > 64) this.log.shift();
    this.log.push((rs ? 'D ' : 'C ') + hex2(byte));
  }

  _command(c) {
    const now = this.sim.cpu.cycles;
    this.busyUntil = now + BUSY_CMD;
    if (c & 0x80) { this.ac = c & 0x7F; this.cgMode = false; }
    else if (c & 0x40) { this.ac = c & 0x3F; this.cgMode = true; }
    else if (c & 0x20) { // Function set
      const dl = !!(c & 0x10);
      if (!this.dl8 && !dl && this.nibbleHigh === true) { /* 4-bit 已生效 */ }
      this.dl8 = dl; this.lines2 = !!(c & 0x08); this.font10 = !!(c & 0x04);
      if (!dl) this.nibbleHigh = true;
    }
    else if (c & 0x10) { // Cursor/display shift
      const disp = !!(c & 0x08), right = !!(c & 0x04);
      if (disp) this.shift = (this.shift + (right ? -1 : 1) + 40) % 40;
      else this.ac = this._step(this.ac, right ? 1 : -1);
    }
    else if (c & 0x08) { this.displayOn = !!(c & 0x04); this.cursorOn = !!(c & 0x02); this.blinkOn = !!(c & 0x01); }
    else if (c & 0x04) { this.entryInc = !!(c & 0x02); this.entryShift = !!(c & 0x01); }
    else if (c & 0x02) { this.ac = 0; this.shift = 0; this.cgMode = false; this.busyUntil = now + BUSY_CLEAR; }
    else if (c & 0x01) { this.ddram.fill(0x20); this.ac = 0; this.shift = 0; this.cgMode = false; this.entryInc = true; this.busyUntil = now + BUSY_CLEAR; }
  }

  _step(ac, d) {
    if (this.cgMode) return (ac + d) & 0x3F;
    if (this.lines2) {
      // 第一行 0x00–0x27，第二行 0x40–0x67
      let a = ac + d;
      if (d > 0) { if (a === 0x28) a = 0x40; else if (a === 0x68) a = 0x00; }
      else { if (a === -1) a = 0x67; else if (a === 0x3F) a = 0x27; }
      return a & 0x7F;
    }
    return (ac + d + 80) % 80;
  }
  _advance() {
    this.ac = this._step(this.ac, this.entryInc ? 1 : -1);
    if (this.entryShift && !this.cgMode) this.shift = (this.shift + (this.entryInc ? 1 : -1) + 40) % 40;
  }
  _writeData(d) {
    this.busyUntil = this.sim.cpu.cycles + BUSY_CMD;
    if (this.cgMode) this.cgram[this.ac & 0x3F] = d & 0x1F;
    else this.ddram[this.ac & 0x7F] = d;
    this._advance();
  }
  _readAtAC() { return this.cgMode ? this.cgram[this.ac & 0x3F] : this.ddram[this.ac & 0x7F]; }

  // 顯示內容：回傳 [行0[16], 行1[16]] 字元碼，以及游標位置
  render() {
    const out = [[], []];
    for (let col = 0; col < 16; col++) {
      const idx = (col + this.shift) % 40;
      out[0].push(this.ddram[idx]);
      out[1].push(this.ddram[0x40 + idx]);
    }
    let cursor = null;
    if (this.displayOn && (this.cursorOn || this.blinkOn) && !this.cgMode) {
      const row = this.ac >= 0x40 ? 1 : 0;
      const col = ((this.ac & 0x3F) - this.shift + 40) % 40;
      if (col < 16) cursor = { row, col };
    }
    return { rows: out, cursor, on: this.displayOn, cgram: this.cgram, blink: this.blinkOn, underline: this.cursorOn };
  }
  setAttached(v) { this.attached = !!v; this.sim.bus.invalidate(); }
  // LCM 插上且 E=1、R/W=1 時會驅動 P0，影響其他用 P0 的程式
  get drivingBus() { return this.attached && (this.bus.latch[3] & 0x03) === 0x03; }
  takeWarnings() { const w = [...this.warnings]; this.warnings.clear(); return w; }
}
